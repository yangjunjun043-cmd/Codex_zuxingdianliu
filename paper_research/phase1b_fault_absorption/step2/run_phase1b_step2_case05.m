function metadata = capture_metadata(projectRoot,modelPath,csvPath,step1Path)
[commitCode,commit] = system(sprintf('git -C "%s" rev-parse HEAD',projectRoot));
[branchCode,branch] = system(sprintf( ...
    'git -C "%s" branch --show-current',projectRoot));
[statusCode,status] = system(sprintf( ...
    'git -C "%s" status --short --untracked-files=all',projectRoot));
if any([commitCode,branchCode,statusCode] ~= 0)
    error('Phase1B:GitMetadata','Unable to read Git metadata.');
end
simulinkInfo = ver('simulink');
metadata = struct( ...
    'git_commit',strtrim(string(commit)), ...
    'git_branch',strtrim(string(branch)), ...
    'git_status',string(status), ...
    'model_sha256',file_sha256(modelPath), ...
    'baseline_csv_sha256',file_sha256(csvPath), ...
    'step1_report_sha256',file_sha256(step1Path), ...
    'run_timestamp',string(datetime('now','TimeZone','Asia/Shanghai', ...
        'Format',"yyyy-MM-dd'T'HH:mm:ssXXX")), ...
    'matlab_version',string(version), ...
    'simulink_version',string(simulinkInfo.Version), ...
    'platform',string(computer));
end

function hash = file_sha256(path)
fileId = fopen(path,'rb');
if fileId < 0
    error('Phase1B:HashFailure','Unable to open %s.',path);
end
cleanup = onCleanup(@() fclose(fileId));
bytes = fread(fileId,Inf,'*uint8');
digester = java.security.MessageDigest.getInstance('SHA-256');
digester.update(bytes);
hashBytes = typecast(digester.digest(),'uint8');
hash = upper(string(reshape(dec2hex(hashBytes,2).',1,[])));
end

function print_key_results(key,validation,summaryPath,workspacePath)
fprintf('INSTRUMENTATION_REPLAY_MAX=%.17g\n',max([ ...
    validation.Cs1_replay_max_abs,validation.Cs2_replay_max_abs, ...
    validation.lambda_replay_max_abs,validation.E_in_replay_max_abs, ...
    validation.E_quad_replay_max_abs,validation.base_in_replay_max_abs]));
fprintf('FORMAL_CASE_REPRODUCED=%d\n',validation.formal_case_reproduced);
fprintf('PROJECTION_CLOSURE_MAX=%.17g\n', ...
    validation.projection_energy_closure_max);
fprintf('TRUE_FAULT_FACTOR=%.17g\n',key.true_fault_factor);
fprintf('M2_FAULT_FACTOR=%.17g\n',key.M2_actual_fault_factor);
fprintf('M2_DELTA_CS_PF=%.17g,%.17g\n', ...
    key.M2_actual_Delta_Cs1_pF,key.M2_actual_Delta_Cs2_pF);
fprintf('RECURSIVE_FAULT_INDUCED_DELTA_CS_PF=%.17g,%.17g\n', ...
    key.recursive_fault_induced_Delta_Cs1_pF, ...
    key.recursive_fault_induced_Delta_Cs2_pF);
fprintf('ETA_GEOM_RAMP_POST=%.17g,%.17g\n', ...
    key.eta_geom_fault_ramp_mean,key.eta_geom_post_fault_mean);
fprintf('COND2_X_RANGE=%.17g,%.17g\n', ...
    key.cond2_X_min,key.cond2_X_max);
fprintf('RATE_LIMIT_CYCLES=%d,%d\n', ...
    key.rate_limit_active_Cs1_cycles,key.rate_limit_active_Cs2_cycles);
fprintf('PROJECTION_CYCLES=%d,%d\n', ...
    key.projection_active_Cs1_cycles,key.projection_active_Cs2_cycles);
fprintf('SUMMARY_CSV=%s\n',summaryPath);
fprintf('WORKSPACE_MAT=%s\n',workspacePath);
end
