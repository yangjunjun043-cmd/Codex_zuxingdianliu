function r = pearson_local(x,y)
if numel(x) < 2 || std(x) == 0 || std(y) == 0
    r = NaN;
    return
end
R = corrcoef(x,y,'Rows','complete');
r = R(1,2);
end

function r = spearman_local(x,y)
rx = tied_rank_local(x);
ry = tied_rank_local(y);
r = pearson_local(rx,ry);
end

function ranks = tied_rank_local(x)
x = x(:);
[sorted,order] = sort(x);
ranksSorted = zeros(size(x));
k = 1;
while k <= numel(sorted)
    last = k;
    while last < numel(sorted) && sorted(last+1) == sorted(k)
        last = last + 1;
    end
    ranksSorted(k:last) = mean(k:last);
    k = last + 1;
end
ranks = zeros(size(x));
ranks(order) = ranksSorted;
end

function validate_sources(summaryTable,cycleDetail,sourceWorkspace)
required = ["condition_id","amplitude_sweep_member","phase_sweep_member", ...
    "fault_factor_true","fault_factor_est","reference_phase_error_deg", ...
    "eta_geom_post","DeltaCs1_LS","DeltaCs2_LS", ...
    "DeltaCs1_fault_induced","DeltaCs2_fault_induced", ...
    "Cs1_pre_estimation_bias_pF","Cs2_pre_estimation_bias_pF", ...
    "fault_retention_error","counterfactual_retention_error_pct", ...
    "false_compensation_fundamental_RMS_A", ...
    "false_compensation_ratio","false_compensation_phase"];
assert(all(ismember(required,string(summaryTable.Properties.VariableNames))), ...
    'Phase1B:MissingField','Step 4 summary is missing required fields.');
assert(height(summaryTable) == 11,'Phase1B:ConditionCount', ...
    'Step 4 summary must contain 11 unique formal conditions.');
assert(numel(unique(summaryTable.condition_id)) == 11, ...
    'Phase1B:ConditionUniqueness','Condition IDs are not unique.');
assert(sum(summaryTable.amplitude_sweep_member) == 6 && ...
    sum(summaryTable.phase_sweep_member) == 6, ...
    'Phase1B:SweepCount','Each formal sweep must contain six points.');
assert(height(cycleDetail) == 1815,'Phase1B:CycleCount', ...
    'Cycle-level source must retain all 1815 rows.');
assert(sourceWorkspace.formalValidation.overall_pass, ...
    'Phase1B:Step4Validation','Step 4 source validation is not PASS.');
end

function validation = validate_results(correlation,prediction,evidence, ...
        figurePaths,amplitude,phase)
validation = struct();
validation.amplitude_n = height(amplitude);
validation.phase_n = height(phase);
validation.correlation_rows = height(correlation);
validation.prediction_rows = height(prediction);
validation.evidence_links = height(evidence);
validation.png_count = sum(isfile(figurePaths(:,1)));
validation.fig_count = sum(isfile(figurePaths(:,2)));
validation.no_missing_meaningful_correlations = all(isfinite( ...
    correlation.pearson_r(correlation.analysis_type == ...
    "correlation_and_linear_fit"))) && all(isfinite( ...
    correlation.spearman_rho(correlation.analysis_type == ...
    "correlation_and_linear_fit")));
validation.all_direction_agreement = all( ...
    prediction.direction_agreement_pct == 100);
validation.eta_amplitude_range = max(amplitude.eta_geom_post) - ...
    min(amplitude.eta_geom_post);
validation.eta_phase_relative_change_pct = 100 * ...
    (phase.eta_geom_post(end)-phase.eta_geom_post(1)) / ...
    phase.eta_geom_post(1);
validation.overall_pass = validation.amplitude_n == 6 && ...
    validation.phase_n == 6 && validation.correlation_rows >= 14 && ...
    validation.prediction_rows == 4 && validation.evidence_links == 5 && ...
    validation.png_count == 6 && validation.fig_count == 6 && ...
    validation.no_missing_meaningful_correlations && ...
    validation.all_direction_agreement;
end

