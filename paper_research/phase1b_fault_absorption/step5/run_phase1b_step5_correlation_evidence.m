bPhase = correlation(correlation.relation_id == "B4_false_comp_phase",:);
fprintf('A1_CS1_R=%.17g RHO=%.17g SLOPE=%.17g R2=%.17g\n', ...
    aCs1.pearson_r,aCs1.spearman_rho,aCs1.linear_slope,aCs1.linear_R2);
