function result = run_phase1b_step5_correlation_evidence
%RUN_PHASE1B_STEP5_CORRELATION_EVIDENCE Analyze frozen Step 4 results only.

step5Root = fileparts(mfilename('fullpath'));
phase1bRoot = fileparts(step5Root);
projectRoot = fileparts(fileparts(phase1bRoot));
step2Root = fullfile(phase1bRoot,'step2');
step3Root = fullfile(phase1bRoot,'step3');
step4Root = fullfile(phase1bRoot,'step4');
figuresRoot = fullfile(step5Root,'figures');
if ~isfolder(figuresRoot)
    mkdir(figuresRoot);
end

frozen = frozen_files(projectRoot,phase1bRoot,step2Root,step3Root,step4Root);
frozen.sha256_before = strings(height(frozen),1);
for k = 1:height(frozen)
    frozen.sha256_before(k) = file_sha256(frozen.path(k));
end

summaryPath = fullfile(step4Root,'controlled_factor_summary.csv');
cyclesPath = fullfile(step4Root,'controlled_factor_cycles.csv');
sourceWorkspacePath = fullfile(step4Root,'controlled_factor_workspace.mat');
summaryTable = readtable(summaryPath,'TextType','string');
cycleDetail = readtable(cyclesPath,'TextType','string');
sourceWorkspace = load(sourceWorkspacePath,'schemaVersion', ...
    'formalValidation','referencePhaseConvention');
case05 = readtable(fullfile(step2Root,'case05_key_metrics.csv'), ...
    'TextType','string');
case06 = readtable(fullfile(step3Root,'case06_key_metrics.csv'), ...
    'TextType','string');

validate_sources(summaryTable,cycleDetail,sourceWorkspace);
amplitude = sortrows(summaryTable(summaryTable.amplitude_sweep_member ~= 0,:), ...
    'fault_factor_true');
phase = sortrows(summaryTable(summaryTable.phase_sweep_member ~= 0,:), ...
    'reference_phase_error_deg');

amplitude.excess_fault_amplitude = amplitude.fault_factor_true - 1;
amplitude.true_increment = amplitude.fault_factor_true - 1;
amplitude.estimated_increment = amplitude.fault_factor_est - 1;
amplitude.lost_increment = amplitude.true_increment - ...
    amplitude.estimated_increment;
amplitude.absolute_fault_factor_loss = abs(amplitude.lost_increment);
amplitude.abs_DeltaCs2_fault_induced = ...
    abs(amplitude.DeltaCs2_fault_induced);
amplitude.false_compensation_RMS_mA = ...
    1e3 * amplitude.false_compensation_fundamental_RMS_A;

phase.lost_increment = phase.fault_factor_true - phase.fault_factor_est;
phase.false_compensation_RMS_mA = ...
    1e3 * phase.false_compensation_fundamental_RMS_A;

correlationSummary = build_correlation_summary(amplitude,phase);
predictionErrorSummary = build_prediction_summary(amplitude,phase);
mechanismEvidenceTable = build_mechanism_evidence( ...
    amplitude,phase,predictionErrorSummary,case05,case06);
figurePaths = generate_phase1b_step5_figures( ...
    figuresRoot,amplitude,phase);

validation = validate_results(correlationSummary,predictionErrorSummary, ...
    mechanismEvidenceTable,figurePaths,amplitude,phase);
frozen.sha256_after = strings(height(frozen),1);
for k = 1:height(frozen)
    frozen.sha256_after(k) = file_sha256(frozen.path(k));
end
frozen.unchanged = frozen.sha256_before == frozen.sha256_after;
validation.frozen_artifacts_unchanged = all(frozen.unchanged);
validation.overall_pass = validation.overall_pass && ...
    validation.frozen_artifacts_unchanged;
if ~validation.overall_pass
    error('Phase1B:Step5Validation','Step 5 validation failed.');
end

correlationPath = fullfile(step5Root,'correlation_summary.csv');
predictionPath = fullfile(step5Root,'prediction_error_summary.csv');
evidencePath = fullfile(step5Root,'mechanism_evidence_table.csv');
workspacePath = fullfile(step5Root,'correlation_workspace.mat');
writetable(correlationSummary,correlationPath);
writetable(predictionErrorSummary,predictionPath);
writetable(mechanismEvidenceTable,evidencePath);

schemaVersion = "phase1b_step5_correlation_v1";
analysisScope = "controlled exploratory evidence; n=6 per sweep";
lostIncrementDefinition = ...
    "true_increment = fault_factor_true - 1; " + ...
    "estimated_increment = fault_factor_est - 1; " + ...
    "lost_increment = true_increment - estimated_increment";
runMetadata = capture_metadata(projectRoot);
result = struct( ...
    'schema_version',schemaVersion, ...
    'analysis_scope',analysisScope, ...
    'lost_increment_definition',lostIncrementDefinition, ...
    'amplitude',amplitude, ...
    'phase',phase, ...
    'correlationSummary',correlationSummary, ...
    'predictionErrorSummary',predictionErrorSummary, ...
    'mechanismEvidenceTable',mechanismEvidenceTable, ...
    'validation',validation, ...
    'frozenManifest',frozen, ...
    'sourceWorkspaceMetadata',sourceWorkspace, ...
    'case05',case05, ...
    'case06',case06, ...
    'figurePaths',figurePaths);
save(workspacePath,'schemaVersion','analysisScope', ...
    'lostIncrementDefinition','amplitude','phase','correlationSummary', ...
    'predictionErrorSummary','mechanismEvidenceTable','validation', ...
    'frozen','sourceWorkspace','case05','case06','figurePaths', ...
    'runMetadata','result','-v7.3');

print_key_results(amplitude,phase,correlationSummary, ...
    predictionErrorSummary,validation);
fprintf('CORRELATION_CSV=%s\n',correlationPath);
fprintf('PREDICTION_CSV=%s\n',predictionPath);
fprintf('EVIDENCE_CSV=%s\n',evidencePath);
fprintf('WORKSPACE_MAT=%s\n',workspacePath);
fprintf('STEP5_CORRELATION_AND_EVIDENCE=PASS\n');
end

function T = build_correlation_summary(amplitude,phase)
rows = cell(0,1);
x = amplitude.excess_fault_amplitude;
rows{end+1} = relationship_row("amplitude","A1_Cs1", ...
    "excess_fault_amplitude","DeltaCs1_fault_induced",x, ...
    amplitude.DeltaCs1_fault_induced,"1","pF", ...
    "Fault-induced Cs1 bias versus fault increment.");
rows{end+1} = relationship_row("amplitude","A1_abs_Cs2", ...
    "excess_fault_amplitude","abs_DeltaCs2_fault_induced",x, ...
    amplitude.abs_DeltaCs2_fault_induced,"1","pF", ...
    "Magnitude of fault-induced Cs2 bias versus fault increment.");
rows{end+1} = relationship_row("amplitude","A3_false_comp_RMS", ...
    "excess_fault_amplitude","false_compensation_RMS",x, ...
    amplitude.false_compensation_RMS_mA,"1","mA", ...
    "False coupling compensation magnitude versus fault increment.");
rows{end+1} = relationship_row("amplitude","A3_lost_increment", ...
    "excess_fault_amplitude","lost_increment",x, ...
    amplitude.lost_increment,"1","fault-factor increment", ...
    "Absolute fault increment removed from the M2 estimate.");
rows{end+1} = relationship_row("amplitude","A3_Cs1_vs_loss", ...
    "DeltaCs1_fault_induced","lost_increment", ...
    amplitude.DeltaCs1_fault_induced,amplitude.lost_increment, ...
    "pF","fault-factor increment", ...
    "Recursive Cs1 bias versus lost fault increment.");
rows{end+1} = relationship_row("amplitude","A3_abs_Cs2_vs_loss", ...
    "abs_DeltaCs2_fault_induced","lost_increment", ...
    amplitude.abs_DeltaCs2_fault_induced,amplitude.lost_increment, ...
    "pF","fault-factor increment", ...
    "Recursive absolute Cs2 bias versus lost fault increment.");
rows{end+1} = invariant_row("amplitude","A4_eta_geom_invariant", ...
    "excess_fault_amplitude","eta_geom_post",x,amplitude.eta_geom_post, ...
    "eta_geom is numerically invariant, so correlation is not a " + ...
    "meaningful mechanism statistic.");

x = phase.reference_phase_error_deg;
rows{end+1} = relationship_row("phase_error","B1_pre_Cs1_bias", ...
    "reference_phase_error","Cs1_pre_estimation_bias",x, ...
    phase.Cs1_pre_estimation_bias_pF,"deg","pF", ...
    "Reference phase error versus normal pre-fault Cs1 bias.");
rows{end+1} = relationship_row("phase_error","B1_pre_Cs2_bias", ...
    "reference_phase_error","Cs2_pre_estimation_bias",x, ...
    phase.Cs2_pre_estimation_bias_pF,"deg","pF", ...
    "Reference phase error versus normal pre-fault Cs2 bias.");
rows{end+1} = relationship_row("phase_error","B2_M2_retention", ...
    "reference_phase_error","M2_fault_retention_error",x, ...
    phase.fault_retention_error,"deg","percent", ...
    "Phase error versus M2 fault retention error.");
rows{end+1} = relationship_row("phase_error","B2_counterfactual_retention", ...
    "reference_phase_error","counterfactual_retention_error",x, ...
    phase.counterfactual_retention_error_pct,"deg","percent", ...
    "Phase error versus retention using counterfactual parameters.");
rows{end+1} = relationship_row("phase_error","B3_eta_geom", ...
    "reference_phase_error","eta_geom_post",x,phase.eta_geom_post, ...
    "deg","1", ...
    "Association is reported with effect size; eta changes only slightly.");
rows{end+1} = relationship_row("phase_error","B4_false_comp_phase", ...
    "reference_phase_error","false_compensation_phase",x, ...
    phase.false_compensation_phase,"deg","deg", ...
    "Reference phase error versus false-compensation direction rotation.");
rows{end+1} = relationship_row("phase_error","B4_false_comp_ratio", ...
    "reference_phase_error","false_compensation_ratio",x, ...
    phase.false_compensation_ratio,"deg","1", ...
    "Reference phase error versus false-compensation amplitude ratio.");
T = struct2table(vertcat(rows{:}),'AsArray',true);
end

function row = relationship_row(sweep,id,predictor,response,x,y,xUnit,yUnit,note)
x = x(:); y = y(:);
valid = isfinite(x) & isfinite(y);
x = x(valid); y = y(valid);
p = polyfit(x,y,1);
yFit = polyval(p,x);
ssRes = sum((y-yFit).^2);
ssTot = sum((y-mean(y)).^2);
if ssTot <= eps(max(abs(y))^2) * numel(y)
    rSquared = NaN;
else
    rSquared = 1 - ssRes/ssTot;
end
row = struct( ...
    'sweep',string(sweep), ...
    'relation_id',string(id), ...
    'analysis_type',"correlation_and_linear_fit", ...
    'predictor',string(predictor), ...
    'response',string(response), ...
    'n',numel(x), ...
    'pearson_r',pearson_local(x,y), ...
    'spearman_rho',spearman_local(x,y), ...
    'linear_slope',p(1), ...
    'linear_intercept',p(2), ...
    'linear_R2',rSquared, ...
    'predictor_min',min(x), ...
    'predictor_max',max(x), ...
    'response_min',min(y), ...
    'response_max',max(y), ...
    'response_range',max(y)-min(y), ...
    'predictor_unit',string(xUnit), ...
    'response_unit',string(yUnit), ...
    'evidence_scope',"controlled exploratory evidence", ...
    'mechanism_note',string(note));
end

function row = invariant_row(sweep,id,predictor,response,x,y,note)
row = relationship_row(sweep,id,predictor,response,x,y,"1","1",note);
row.analysis_type = "descriptive_invariant";
row.pearson_r = NaN;
row.spearman_rho = NaN;
row.linear_slope = NaN;
row.linear_intercept = NaN;
row.linear_R2 = NaN;
end

function T = build_prediction_summary(amplitude,phase)
rows = [ ...
    prediction_row("amplitude","Cs1",amplitude.DeltaCs1_LS, ...
        amplitude.DeltaCs1_fault_induced); ...
    prediction_row("amplitude","Cs2",amplitude.DeltaCs2_LS, ...
        amplitude.DeltaCs2_fault_induced); ...
    prediction_row("phase_error","Cs1",phase.DeltaCs1_LS, ...
        phase.DeltaCs1_fault_induced); ...
    prediction_row("phase_error","Cs2",phase.DeltaCs2_LS, ...
        phase.DeltaCs2_fault_induced)];
T = struct2table(rows,'AsArray',true);
end

function row = prediction_row(sweep,parameter,predicted,actual)
predicted = predicted(:); actual = actual(:);
errorValue = predicted - actual;
relativeErrorPct = 100 * abs(errorValue) ./ max(abs(actual),eps);
row = struct( ...
    'sweep',string(sweep), ...
    'parameter',string(parameter), ...
    'n',numel(actual), ...
    'RMSE_pF',sqrt(mean(errorValue.^2)), ...
    'MAE_pF',mean(abs(errorValue)), ...
    'max_absolute_error_pF',max(abs(errorValue)), ...
    'max_relative_error_pct',max(relativeErrorPct), ...
    'pearson_r',pearson_local(predicted,actual), ...
    'spearman_rho',spearman_local(predicted,actual), ...
    'direction_agreement_pct',100*mean(sign(predicted) == sign(actual)), ...
    'prediction_definition',"static Delta c_LS,f", ...
    'actual_definition',"recursive fault-branch minus counterfactual-branch bias", ...
    'evidence_scope',"controlled exploratory evidence");
end

