    max(prediction.RMSE_pF),max(prediction.max_relative_error_pct));
fprintf('AMPLITUDE_ETA_RANGE=%.17g LOST_INCREMENT_RANGE=%.17g,%.17g\n', ...
    max(amplitude.eta_geom_post)-min(amplitude.eta_geom_post), ...
    min(amplitude.lost_increment), ...
    max(amplitude.lost_increment));
fprintf('PHASE_ETA_REL_CHANGE_PCT=%.17g ETA_R=%.17g PHASE_ROTATION_R=%.17g\n', ...
    validation.eta_phase_relative_change_pct,bEta.pearson_r, ...
    bPhase.pearson_r);
fprintf('PHASE_RETENTION_RANGE=%.17g,%.17g CF_RANGE=%.17g,%.17g\n', ...
    min(phase.fault_retention_error),max(phase.fault_retention_error), ...
    min(phase.counterfactual_retention_error_pct), ...
    max(phase.counterfactual_retention_error_pct));
