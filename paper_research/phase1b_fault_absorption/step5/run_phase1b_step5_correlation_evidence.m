    case06.true_fault_factor(1);
rows = [ ...
    evidence_row("E1","r_fault", ...
        "projection onto col(X)","directly verified", ...
        sprintf(['Step 2/3 projection closure <= 5.50e-15; Step 4 ' ...
        'eta_post %.9f to %.9f.'],min(amplitude.eta_geom_post), ...
        max(phase.eta_geom_post)), ...
        "Geometry is conditional on the frozen two-column X/reference model."); ...
    evidence_row("E2","projection onto col(X)", ...
        "Delta c_LS,f","directly verified", ...
        "X*Delta c_LS,f reproduces the projected component by construction " + ...
        "and passed the Step 2/3 projection-fit checks.", ...
        "Static LS describes blockwise equivalent bias, not recursive timing."); ...
    evidence_row("E3","Delta c_LS,f", ...
        "recursive false Cs bias","strongly supported", ...
        sprintf(['Amplitude-sweep maximum RMSE %.6g pF, maximum relative ' ...
        'error %.6g%%, direction agreement 100%%.'], ...
        maxAmpRmse,maxAmpRelative), ...
        "Only six deterministic points per sweep; recursion and state history remain separate."); ...
    evidence_row("E4","recursive false Cs bias", ...
        "false coupling compensation","directly verified", ...
        sprintf(['Compensation RMS rises %.6g to %.6g mA while its amplitude ' ...
        'ratio stays %.6f to %.6f.'], ...
        min(amplitude.false_compensation_RMS_mA), ...
        max(amplitude.false_compensation_RMS_mA), ...
        min(amplitude.false_compensation_ratio), ...
        max(amplitude.false_compensation_ratio)), ...
        "Mapping is evaluated for the frozen B-phase extraction equation."); ...
    evidence_row("E5","false coupling compensation", ...
        "fault increment loss","directly verified", ...
        sprintf(['Case05/Case06 counterfactual recovery residuals are %.6g ' ...
