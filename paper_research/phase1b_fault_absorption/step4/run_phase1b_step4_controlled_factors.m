function assert_frozen_integrity(frozen)
for k = 1:height(frozen)
    actual = file_sha256(frozen.path(k));
    if actual ~= frozen.expected_sha256(k)
        error('Phase1B:Integrity','Frozen file changed: %s.',frozen.name(k));
    end
end
end

function metadata = capture_metadata(projectRoot,frozen)
[commitCode,commit] = system(sprintf('git -C "%s" rev-parse HEAD',projectRoot));
[branchCode,branch] = system(sprintf( ...
    'git -C "%s" branch --show-current',projectRoot));
[statusCode,status] = system(sprintf( ...
    'git -C "%s" status --short --untracked-files=all',projectRoot));
if any([commitCode,branchCode,statusCode] ~= 0)
    error('Phase1B:GitMetadata','Unable to read Git metadata.');
end
simulinkInfo = ver('simulink');
metadata = struct( ...
    'git_commit',strtrim(string(commit)), ...
    'git_branch',strtrim(string(branch)), ...
    'git_status',string(status), ...
    'frozen_manifest',frozen, ...
    'run_timestamp',string(datetime('now','TimeZone','Asia/Shanghai', ...
        'Format',"yyyy-MM-dd'T'HH:mm:ssXXX")), ...
    'matlab_version',string(version), ...
    'simulink_version',string(simulinkInfo.Version), ...
    'platform',string(computer));
end

function hash = file_sha256(path)
fileId = fopen(path,'rb');
if fileId < 0
    error('Phase1B:HashFailure','Unable to open %s.',path);
end
cleanupObj = onCleanup(@() fclose(fileId));
bytes = fread(fileId,Inf,'*uint8');
clear cleanupObj
digester = java.security.MessageDigest.getInstance('SHA-256');
digester.update(bytes);
hashBytes = typecast(digester.digest(),'uint8');
hash = upper(string(reshape(dec2hex(hashBytes,2).',1,[])));
end

function print_key_results(summaryTable,baseline,formal,summaryPath,workspacePath)
amplitude = sortrows(summaryTable(summaryTable.amplitude_sweep_member,:), ...
    'fault_factor_target');
phase = sortrows(summaryTable(summaryTable.phase_sweep_member,:), ...
    'reference_phase_error_deg');
fprintf('BASELINE_REPRODUCTION_MAX=%.17g\n',baseline.max_abs);
fprintf('FORMAL_CONDITION_COUNTS=%d,%d,%d\n', ...
    formal.unique_condition_count,formal.amplitude_condition_count, ...
    formal.phase_condition_count);
fprintf('AMPLITUDE_ETA_POST_RANGE=%.17g,%.17g\n', ...
    min(amplitude.eta_geom_post),max(amplitude.eta_geom_post));
fprintf('AMPLITUDE_FAULT_BIAS_CS1_RANGE=%.17g,%.17g\n', ...
    min(amplitude.DeltaCs1_fault_induced), ...
    max(amplitude.DeltaCs1_fault_induced));
fprintf('PHASE_ETA_POST_RANGE=%.17g,%.17g\n', ...
    min(phase.eta_geom_post),max(phase.eta_geom_post));
fprintf('PHASE_RETENTION_ERROR_RANGE=%.17g,%.17g\n', ...
    min(phase.fault_retention_error),max(phase.fault_retention_error));
fprintf('RATE_LIMIT_MAX=%d PROJECTION_MAX=%d\n', ...
    max(summaryTable.rate_limit_cycles),max(summaryTable.projection_cycles));
fprintf('SUMMARY_CSV=%s\n',summaryPath);
fprintf('WORKSPACE_MAT=%s\n',workspacePath);
end
