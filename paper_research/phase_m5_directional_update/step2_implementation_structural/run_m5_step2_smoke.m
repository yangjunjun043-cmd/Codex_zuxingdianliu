function note = segment_note(segmentName)
if segmentName == "POST_FAULT"
    note = "Unavailable: the frozen Case05/06 fault persists to run end.";
else
    note = "Descriptive structural smoke only; no performance threshold.";
end
end

function value = safe_max_abs(values)
values = values(isfinite(values));
if isempty(values)
    value = NaN;
else
    value = max(abs(values));
end
end

