function pass = case_pass(summaryTable,caseName)
rows = summaryTable.case_name == caseName & summaryTable.segment == "ALL";
pass = nnz(rows) == 4 && all(summaryTable.smoke_pass(rows));
end

function tableOut = capture_frozen_hashes(matlabRoot)
[roles,names,expected] = frozen_hash_definition();
actual = strings(size(names));
for k = 1:numel(names)
    actual(k) = file_sha256(fullfile(matlabRoot,names(k)));
end
tableOut = table(roles,names,expected,actual, ...
    'VariableNames',{'role','file_name','expected_sha256','sha256'});
end

function audit = build_hash_audit(before,after)
audit = table( ...
    before.role,before.file_name,before.expected_sha256, ...
    before.sha256,after.sha256, ...
    before.sha256 == before.expected_sha256, ...
    after.sha256 == before.expected_sha256, ...
    before.sha256 == after.sha256, ...
    'VariableNames',{'role','file_name','expected_sha256', ...
    'sha256_before','sha256_after','before_matches_expected', ...
    'after_matches_expected','unchanged_during_run'});
audit.pass = audit.before_matches_expected & ...
    audit.after_matches_expected & audit.unchanged_during_run;
end

