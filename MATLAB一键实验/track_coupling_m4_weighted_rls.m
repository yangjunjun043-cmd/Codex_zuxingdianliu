        Ein,Equad,baseIn,baseInStar,baseIncrementCandidate, ...
        baseIncrementApplied,evidence,deltaLocal,deltaM2Raw, ...
        deltaRaw,deltaAfterRate,deltaApplied,totalSuppression, ...
        informationSuppression,rateSuppression, ...
        projectionSuppression,JIncrementRaw,JIncrementApplied, ...
        hIncrementRaw,hIncrementApplied,rateLimitActive, ...
        projectionActive,direction,J,h,forcedUpdateWeight, ...
        directionDiagnosticsEnabled)
row = struct( ...
    'time_s',time, ...
    'Cs1_pF',c(1), ...
    'Cs2_pF',c(2), ...
    'lambda',lambda, ...
    'innovation_scalar',innovation, ...
    'local_ls_Cs1_pF',localLs(1), ...
    'local_ls_Cs2_pF',localLs(2), ...
    'E_in',Ein, ...
    'E_quad',Equad, ...
    'base_in',baseIn, ...
    'base_in_candidate',baseInStar, ...
    'base_in_increment_candidate',baseIncrementCandidate, ...
    'base_in_increment_applied',baseIncrementApplied, ...
    'evidence_ratio_base',evidence.ratio_base, ...
    'evidence_ratio_quad',evidence.ratio_quad, ...
    'evidence_background_excess',evidence.background_excess, ...
    'evidence_phase_weight',evidence.phase_weight, ...
    'fault_evidence_score',evidence.score, ...
    'update_weight',evidence.update_weight, ...
    'delta_c_local_1',deltaLocal(1), ...
    'delta_c_local_2',deltaLocal(2), ...
    'delta_c_m2_raw_1',deltaM2Raw(1), ...
    'delta_c_m2_raw_2',deltaM2Raw(2), ...
    'delta_c_raw_1',deltaRaw(1), ...
    'delta_c_raw_2',deltaRaw(2), ...
    'delta_c_after_rate_1',deltaAfterRate(1), ...
    'delta_c_after_rate_2',deltaAfterRate(2), ...
    'delta_c_applied_1',deltaApplied(1), ...
    'delta_c_applied_2',deltaApplied(2), ...
    'delta_c_suppressed_1',totalSuppression(1), ...
    'delta_c_suppressed_2',totalSuppression(2), ...
    'delta_c_information_suppressed_1',informationSuppression(1), ...
    'delta_c_information_suppressed_2',informationSuppression(2), ...
    'delta_c_rate_suppressed_1',rateSuppression(1), ...
    'delta_c_rate_suppressed_2',rateSuppression(2), ...
    'delta_c_projection_suppressed_1',projectionSuppression(1), ...
    'delta_c_projection_suppressed_2',projectionSuppression(2), ...
    'J_increment_norm_raw',norm(JIncrementRaw,'fro'), ...
    'J_increment_norm_applied',norm(JIncrementApplied,'fro'), ...
    'h_increment_norm_raw',norm(hIncrementRaw), ...
    'h_increment_norm_applied',norm(hIncrementApplied), ...
    'rate_limit_active',logical(rateLimitActive), ...
    'projection_active',logical(projectionActive), ...
    'm4_evidence_valid',logical(evidence.valid), ...
    'fault_direction_candidate_1',direction.fault_direction(1), ...
    'fault_direction_candidate_2',direction.fault_direction(2), ...
    'direction_candidate_valid',logical(direction.valid), ...
    'cos_local_fault',direction.cos_local_fault, ...
    'cos_raw_fault',direction.cos_raw_fault, ...
    'delta_c_parallel_1',direction.delta_parallel(1), ...
    'delta_c_parallel_2',direction.delta_parallel(2), ...
    'delta_c_perpendicular_1',direction.delta_perpendicular(1), ...
    'delta_c_perpendicular_2',direction.delta_perpendicular(2), ...
    'R_condition_number',direction.R_condition_number, ...
    'J_11',J(1,1), ...
    'J_12',J(1,2), ...
    'J_21',J(2,1), ...
    'J_22',J(2,2), ...
    'h_1',h(1), ...
    'h_2',h(2), ...
    'J_increment_raw_11',JIncrementRaw(1,1), ...
    'J_increment_raw_12',JIncrementRaw(1,2), ...
    'J_increment_raw_21',JIncrementRaw(2,1), ...
    'J_increment_raw_22',JIncrementRaw(2,2), ...
    'J_increment_applied_11',JIncrementApplied(1,1), ...
    'J_increment_applied_12',JIncrementApplied(1,2), ...
    'J_increment_applied_21',JIncrementApplied(2,1), ...
    'J_increment_applied_22',JIncrementApplied(2,2), ...
    'h_increment_raw_1',hIncrementRaw(1), ...
    'h_increment_raw_2',hIncrementRaw(2), ...
    'h_increment_applied_1',hIncrementApplied(1), ...
    'h_increment_applied_2',hIncrementApplied(2), ...
    'forced_update_weight_active',logical(~isnan(forcedUpdateWeight)), ...
    'direction_diagnostics_enabled',logical(directionDiagnosticsEnabled));
end
