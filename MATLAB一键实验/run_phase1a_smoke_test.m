function row = regression_row(caseName,algorithmMode,metricName, ...
        historicalValue,newValue,reference)
absoluteDifference = abs(newValue-historicalValue);
relativeDifference = absoluteDifference/(abs(historicalValue)+eps);
absoluteTolerance = reference.absolute_tolerance;
relativeTolerance = reference.relative_tolerance;
passed = absoluteDifference <= ...
    absoluteTolerance+relativeTolerance*abs(historicalValue);
row = {table(caseName,algorithmMode,metricName,historicalValue,newValue, ...
    absoluteDifference,relativeDifference,absoluteTolerance, ...
    relativeTolerance,passed, ...
    'VariableNames',{'case_name','algorithm_mode','metric_name', ...
    'historical_value','new_value','absolute_difference', ...
    'relative_difference','absolute_tolerance','relative_tolerance', ...
    'pass'})};
end

function value = metric_value(metrics,mode,metricName)
row = metrics.algorithm_mode == mode;
if nnz(row) ~= 1
    error('Phase1A:MissingSmokeMetric', ...
        'Expected one metric row for algorithm %s.',mode);
end
value = metrics.(metricName)(row);
end

function metadata = current_run_metadata(modelSha256)
[commitStatus,gitCommit] = system('git rev-parse HEAD');
[branchStatus,gitBranch] = system('git branch --show-current');
[statusCode,gitStatus] = system( ...
    'git status --short --untracked-files=all');
if commitStatus ~= 0 || branchStatus ~= 0 || statusCode ~= 0
    error('Phase1A:GitMetadataFailure', ...
        'Unable to read Git metadata for the smoke test.');
end
dirtyStatus = "CLEAN";
if strlength(strtrim(string(gitStatus))) > 0
    dirtyStatus = "DIRTY";
end
metadata = struct( ...
    'model_sha256',modelSha256, ...
    'run_timestamp',string(datetime('now','TimeZone','Asia/Shanghai', ...
    'Format',"yyyy-MM-dd'T'HH:mm:ssXXX")), ...
    'git_commit',strtrim(string(gitCommit)), ...
    'git_branch',strtrim(string(gitBranch)), ...
    'git_dirty_status',dirtyStatus, ...
    'matlab_version',string(version), ...
    'simulink_version',string(ver('simulink').Version), ...
    'platform',string(computer));
end

function hash = file_sha256(path)
fileId = fopen(path,'rb');
if fileId < 0
    error('Phase1A:HashFailure','Unable to compute AutoComp9 SHA-256.');
end
cleanup = onCleanup(@() fclose(fileId));
bytes = fread(fileId,Inf,'*uint8');
digester = java.security.MessageDigest.getInstance('SHA-256');
digester.update(bytes);
hashBytes = typecast(digester.digest(),'uint8');
hash = upper(string(reshape(dec2hex(hashBytes,2).',1,[])));
end

function label = pass_label(value)
if value
    label = "PASS";
else
    label = "FAIL";
end
end
