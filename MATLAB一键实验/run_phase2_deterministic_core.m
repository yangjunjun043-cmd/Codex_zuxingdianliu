end

function label = monotonic_label(values)
tolerance = 1e-12;
if all(diff(values) >= -tolerance)
    label = "is nondecreasing";
elseif all(diff(values) <= tolerance)
    label = "is nonincreasing";
else
    label = "is non-monotonic";
end
end

function value = safe_corr(x,y)
if numel(x) < 2 || numel(unique(x)) < 2 || numel(unique(y)) < 2
    value = NaN;
else
    matrix = corrcoef(x,y);
    value = matrix(1,2);
end
end

function textValue = code_list(values)
if isempty(values)
    textValue = "none";
else
    textValue = "`"+strjoin(values,"`, `")+"`";
end
end

