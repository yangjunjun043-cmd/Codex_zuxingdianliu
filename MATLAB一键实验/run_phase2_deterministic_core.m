groupConditions = conditions(conditions.experiment_group == group,:);
for k = 1:height(groupConditions)
    id = groupConditions.condition_id(k);
    level = groupConditions.(char(registryField))(k);
    for mode = ["M0","M2","M3","M4"]
        current = one_result(rows,id,mode);
        fprintf(fileId,['| `%s` | %.6g | %s | %.6f | %.6f | ' ...
            '%.6f / %.6f | %.6f | %.6g | %.6g | %.6g |\n'], ...
            id,level,mode,current.Cs1_RMSE_pF,current.Cs2_RMSE_pF, ...
            current.Cs1_max_abs_error_pF,current.Cs2_max_abs_error_pF, ...
            current.B_resistive_fundamental_error_pct, ...
            current.hard_gate_active_ratio,current.mean_update_weight, ...
            current.unnecessary_suppression_ratio);
    end
end
fprintf(fileId,'\n');
end

function row = one_result(rows,conditionId,algorithmId)
match = rows.condition_id == conditionId & rows.algorithm_id == algorithmId;
if nnz(match) ~= 1
    error('Phase2:ReportRowCardinality', ...
        'Expected one row for %s/%s.',conditionId,algorithmId);
end
row = rows(match,:);
end

function [analysis,missIds,triggerIds] = analyze_fault_sweep(rows)
m2 = rows(rows.algorithm_id == "M2",:);
m3 = rows(rows.algorithm_id == "M3",:);
m4 = rows(rows.algorithm_id == "M4",:);
missIds = m3.condition_id(m3.hard_gate_active_ratio == 0);
triggerIds = m3.condition_id(m3.hard_gate_active_ratio > 0);

families = unique(m4.anchor_case,'stable');
weightParts = strings(0,1);
absorptionParts = strings(0,1);
for k = 1:numel(families)
    family = families(k);
    current4 = m4(m4.anchor_case == family,:);
    current2 = m2(m2.anchor_case == family,:);
    [factor,order] = sort(current4.target_value);
    g = current4.mean_update_weight(order);
    bias = current2.Cs_fault_induced_bias_norm_pF(order);
    weightParts(end+1) = family+": mean g "+ ...
        monotonic_label(g)+sprintf(' (r=%.4f)',safe_corr(factor,g)); %#ok<AGROW>
    absorptionParts(end+1) = family+": M2 bias norm "+ ...
        monotonic_label(bias)+sprintf(' (r=%.4f)', ...
        safe_corr(factor,bias)); %#ok<AGROW>
end
m4BetterRetention = abs(m4.fault_retention_error_pct) < ...
    abs(m2.fault_retention_error_pct);
m4LowerBias = m4.Cs_fault_induced_bias_norm_pF < ...
    m2.Cs_fault_induced_bias_norm_pF;
m4VsM3Retention = abs(m4.fault_retention_error_pct) < ...
    abs(m3.fault_retention_error_pct);
m4VsM3Bias = m4.Cs_fault_induced_bias_norm_pF < ...
    m3.Cs_fault_induced_bias_norm_pF;
analysis = struct( ...
    'm4_weight_statement',"M4 continuous-response audit: "+ ...
        strjoin(weightParts,"; ")+". Monotonicity is descriptive, not required.", ...
    'm2_absorption_statement',"M2 severity audit: "+ ...
        strjoin(absorptionParts,"; ")+".", ...
    'm4_vs_m2_statement',sprintf([ ...
        'M4 versus M2: lower absolute retention error in %d/%d rows and ' ...
        'lower fault-induced bias norm in %d/%d rows.'], ...
        nnz(m4BetterRetention),height(m4),nnz(m4LowerBias),height(m4)), ...
    'm4_vs_m3_statement',sprintf([ ...
        'M4 versus M3: lower absolute retention error in %d/%d rows and ' ...
        'lower fault-induced bias norm in %d/%d rows. The complementary ' ...
        'rows are the observed M4 cost; no threshold was retuned.'], ...
        nnz(m4VsM3Retention),height(m4),nnz(m4VsM3Bias),height(m4)), ...
    'support_statement',sprintf([ ...
        'Phase 1C support: M4 improves M2 absolute fault retention in ' ...
        '%d/%d registered amplitude rows and reduces M2 fault-induced ' ...
        'bias norm in %d/%d rows.'],nnz(m4BetterRetention),height(m4), ...
        nnz(m4LowerBias),height(m4)), ...
    'limit_statement',sprintf([ ...
        'Phase 1C limitation: M4 does not dominate M3; M3 has equal or ' ...
        'better absolute retention in %d/%d rows and equal or lower bias ' ...
        'norm in %d/%d rows.'],height(m4)-nnz(m4VsM3Retention),height(m4), ...
        height(m4)-nnz(m4VsM3Bias),height(m4)));
end

function textValue = snr_analysis(rows)
parts = strings(0,1);
for mode = ["M0","M2","M3","M4"]
    current = rows(rows.algorithm_id == mode,:);
    [levels,order] = sort(current.target_value,'descend');
    values = abs(current.B_resistive_fundamental_error_pct(order));
    parts(end+1) = sprintf( ...
        '%s |B error| spans %.6f%% to %.6f%% over %s dB', ...
        mode,min(values),max(values),strjoin(string(levels.'),',')); %#ok<AGROW>
end
textValue = "SNR descriptive audit: "+strjoin(parts,"; ")+ ...
    ". Tracking RMSE and M3/M4 protection behavior are retained in the table.";
end

function textValue = phase_analysis(rows)
parts = strings(0,1);
for mode = ["M0","M2","M3","M4"]
    current = rows(rows.algorithm_id == mode,:);
    [levels,order] = sort(current.target_value);
    values = abs(current.B_resistive_fundamental_error_pct(order));
    parts(end+1) = sprintf( ...
        '%s |B error| %.6f%% at %.2f deg -> %.6f%% at %.2f deg', ...
        mode,values(1),levels(1),values(end),levels(end)); %#ok<AGROW>
