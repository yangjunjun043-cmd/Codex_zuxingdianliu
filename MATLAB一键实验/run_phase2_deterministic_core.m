function run = execute_condition(conditionRegistry, ...
        executionRegistry,conditionId,allowAuthorizedPending)
if nargin < 4
    allowAuthorizedPending = false;
end
conditionId = string(conditionId);
match = conditionRegistry.condition_id == conditionId;
if nnz(match) ~= 1
    error('Phase2:ConditionRegistryCardinality', ...
        'condition_id %s occurs %d times in condition registry.', ...
        conditionId,nnz(match));
end
row = conditionRegistry(match,:);
if string(row.registry_state) ~= "FROZEN" || truthy(row.is_blocked)
    error('Phase2:ConditionNotExecutable', ...
        'Condition %s is not a frozen executable row.',conditionId);
end

executionRows = executionRegistry( ...
    executionRegistry.condition_id == conditionId & ...
    executionRegistry.record_type == "MAIN_ALGORITHM_EVALUATION",:);
expectedModes = ["M0";"M2";"M3";"M4"];
if height(executionRows) ~= 4 || ...
        ~isequal(sort(string(executionRows.algorithm_id)),expectedModes)
    error('Phase2:ExecutionRegistryCardinality', ...
        'Condition %s must map to exactly M0/M2/M3/M4.',conditionId);
end
statuses = string(executionRows.execution_status);
pendingAuthorized = allowAuthorizedPending && ...
    all(statuses == "PENDING_GATE") && ...
    ismember(string(row.experiment_group), ...
    ["CSELF_MISMATCH","CSAC_MISMATCH"]);
if any(statuses ~= "READY") && ~pendingAuthorized
    error('Phase2:ExecutionRegistryStatus', ...
        'Condition %s has a non-READY evaluation.',conditionId);
end

anchor = find_anchor(conditionRegistry,row);
[targetFactor,targetValue] = target_from_registry(row);
anchorPass = non_target_anchor_match(row,anchor,targetFactor);

[physicalCfg,algorithmCfg,dataCfg,windowCfg,provenance] = ...
    build_configs(row,targetFactor,targetValue);
signals = build_registry_signals(row,physicalCfg);
if string(row.experiment_group) == "CSAC_MISMATCH"
    [data,cleanData,noise] = simulate_registry_csac_condition( ...
        row,physicalCfg,dataCfg.noise_seed);
else
    [data,cleanData,noise] = simulate_registry_condition( ...
        physicalCfg,signals,dataCfg.noise_seed);
end
ref = reconstruct_refs_from_b(data.t,data.ub,algorithmCfg.f, ...
    algorithmCfg.init_start,algorithmCfg.init_end, ...
    algorithmCfg.phase_error_deg);
mappingPass = anchorPass && mapping_audit(row,physicalCfg, ...
    algorithmCfg,signals,data,cleanData,noise,ref);

isFault = string(row.fault_mode) == "PERSISTENT_B_RESISTIVE";
if isFault
    counterfactualData = remove_fault_component(data,signals.fault_scale);
else
    counterfactualData = struct();
end

dataSignature = physical_data_signature(data);
truthSignature = truth_signature(data,signals);
windowSignature = struct_signature(windowCfg);
referenceSignature = reference_signature(ref);
sharedSignature = bytes_sha256(unicode2native(char( ...
    dataSignature+truthSignature+windowSignature+referenceSignature), ...
    'UTF-8'));

resultRows = empty_result_table();
algorithmResults = struct();
counterfactualResults = struct();
for mode = expectedModes.'
    result = run_phase1a_algorithm(mode,data,ref,algorithmCfg, ...
        repmat(row.Cself_algorithm_pF,1,3));
    algorithmResults.(char(mode)) = result;
    if isFault
        counterfactual = run_phase1a_algorithm(mode, ...
            counterfactualData,ref,algorithmCfg, ...
            repmat(row.Cself_algorithm_pF,1,3));
        counterfactualResults.(char(mode)) = counterfactual;
    else
        counterfactual = struct();
    end
    metrics = extract_frozen_metrics(mode,result,counterfactual, ...
        data,algorithmCfg,windowCfg,isFault);
    requiredPass = required_outputs_exist(result) && ...
        required_metrics_exist(mode,metrics,isFault);
    numericalFailure = ~core_outputs_finite(data,ref,result) || ...
        ~requiredPass;
    notes = provenance_note(provenance,isFault,row);
    resultRows = [resultRows;make_result_row(conditionId, ...
        row.experiment_group,mode,targetFactor,targetValue, ...
        row.anchor_case,sharedSignature,metrics,numericalFailure,~requiredPass, ...
        mappingPass,true,false,notes)]; %#ok<AGROW>
end

sharedDataPass = numel(unique(resultRows.data_signature)) == 1 && ...
    all(resultRows.data_signature == sharedSignature);
resultRows.shared_data_pass(:) = sharedDataPass;
run = struct( ...
    'condition_id',conditionId, ...
    'condition_registry_row',row, ...
    'execution_registry_rows',executionRows, ...
    'anchor_registry_row',anchor, ...
    'target_factor',targetFactor, ...
    'target_value',targetValue, ...
    'physical_truth_config',physicalCfg, ...
    'algorithm_assumption_config',algorithmCfg, ...
    'data_generation_config',dataCfg, ...
    'evaluation_window_config',windowCfg, ...
    'provenance',provenance, ...
    'signals',signals, ...
    'data',data, ...
    'clean_data',cleanData, ...
    'noise',noise, ...
    'reference',ref, ...
    'data_signature',dataSignature, ...
    'truth_signature',truthSignature, ...
    'window_signature',windowSignature, ...
    'reference_signature',referenceSignature, ...
    'shared_execution_signature',sharedSignature, ...
    'algorithm_results',algorithmResults, ...
    'counterfactual_results',counterfactualResults, ...
    'registry_mapping_pass',mappingPass, ...
    'shared_data_pass',sharedDataPass, ...
    'rows',resultRows);
end

function anchor = find_anchor(registry,row)
isAnchor = false(height(registry),1);
for k = 1:height(registry)
    isAnchor(k) = truthy(registry.is_anchor(k));
end
match = registry.anchor_case == row.anchor_case & isAnchor;
if nnz(match) ~= 1
    error('Phase2:AnchorCardinality', ...
        'Expected one anchor for %s.',string(row.anchor_case));
end
anchor = registry(match,:);
end

function [name,value] = target_from_registry(row)
switch string(row.experiment_group)
    case "FAULT_AMPLITUDE"
        name = "fault_factor"; value = row.fault_factor;
    case "SNR"
        name = "SNR_dB"; value = row.SNR_dB;
    case "REFERENCE_PHASE"
        name = "reference_phase_error_deg";
        value = row.reference_phase_error_deg;
    case "THIRD_HARMONIC"
        name = "h3_ratio"; value = row.h3_ratio;
    case "NEGATIVE_SEQUENCE"
        name = "negative_sequence_pu";
        value = row.negative_sequence_pu;
    case "CSELF_MISMATCH"
        name = "Cself_truth_pF";
        value = row.Cself_truth_pF;
    case "CSAC_MISMATCH"
        name = "CsAC_truth_pF";
        value = row.CsAC_truth_pF;
    otherwise
        error('Phase2:UnsupportedFamily', ...
            'Unsupported deterministic family: %s.',row.experiment_group);
end
if ~(isnumeric(value) && isscalar(value) && ~isnan(value))
    error('Phase2:InvalidTarget','Target %s is not a valid scalar.',name);
end
end

function pass = non_target_anchor_match(row,anchor,targetName)
physicalFields = [ ...
    "fault_factor","fault_start_s","fault_ramp_up_s", ...
    "fault_ramp_end_s","fault_mode", ...
    "Cs1_initial_pF","Cs2_initial_pF","Cs1_final_pF", ...
    "Cs2_final_pF","drift_direction_id","drift_delta_Cs1_pF", ...
    "drift_delta_Cs2_pF","drift_total_norm_pF", ...
    "drift_rate_multiplier","drift_start_s","drift_end_s", ...
    "drift_duration_s","SNR_dB","noise_mode", ...
    "deterministic_seed","reference_phase_error_deg", ...
    "h3_ratio","h3_phase_deg","negative_sequence_pu", ...
    "negative_sequence_convention_status","Cself_truth_pF", ...
    "Cself_algorithm_pF","CsAC_truth_pF", ...
    "evaluation_window_set_id","simulation_stop_s"];
pass = true;
for name = physicalFields
    if name == targetName || ...
            (targetName == "SNR_dB" && name == "noise_mode")
        continue
    end
    if ~physical_field_equal(name,row.(char(name)),anchor.(char(name)))
        pass = false;
        return
    end
end
end

function equal = physical_field_equal(name,conditionValue,anchorValue)
% The frozen Case06 anchor stores an unspecified base-rate multiplier as
% NaN, while its one-factor descendants explicitly encode the same nominal
% trajectory rate as 1. This is a schema normalization, not a factor change.
if name == "drift_rate_multiplier" && isnumeric(anchorValue) && ...
        isnan(anchorValue) && isnumeric(conditionValue) && ...
        conditionValue == 1
    equal = true;
else
    equal = registry_value_equal(conditionValue,anchorValue);
end
end

function equal = registry_value_equal(a,b)
if isnumeric(a) && isnumeric(b)
    equal = (isnan(a) && isnan(b)) || ...
        (isfinite(a) && isfinite(b) && abs(a-b) <= 1e-12);
else
    equal = string(a) == string(b);
end
end

