    ". Rapid growth, non-monotonicity, or gate activity is preserved as observed.";
end

function textValue = harmonic_analysis(rows)
parts = strings(0,1);
for mode = ["M0","M2","M3","M4"]
    current = rows(rows.algorithm_id == mode,:);
    maxError = max(abs(current.B_resistive_fundamental_error_pct));
    maxRmse = max(hypot(current.Cs1_RMSE_pF,current.Cs2_RMSE_pF));
    parts(end+1) = sprintf('%s max |B error| %.6f%%, max Cs RMSE norm %.6f pF', ...
        mode,maxError,maxRmse); %#ok<AGROW>
end
textValue = "Harmonic-amplitude audit: "+strjoin(parts,"; ")+".";
end

function textValue = negative_sequence_analysis(rows)
parts = strings(0,1);
for mode = ["M0","M2","M3","M4"]
    current = rows(rows.algorithm_id == mode,:);
    [levels,order] = sort(current.target_value);
    values = abs(current.B_resistive_fundamental_error_pct(order));
    parts(end+1) = sprintf('%s |B error| %s%% at Vneg %s',mode, ...
