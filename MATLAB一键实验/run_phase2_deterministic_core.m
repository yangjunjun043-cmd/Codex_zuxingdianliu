function signals = build_registry_signals(row,cfg)
t = (0:cfg.Ts:cfg.StopTime).';
base = generate_coupling_signals(t,char(row.anchor_case), ...
    row.deterministic_seed);
signals = base;
if string(row.fault_mode) == "PERSISTENT_B_RESISTIVE"
    progress = smooth_step(t,row.fault_start_s,row.fault_ramp_end_s);
    signals.fault_scale = 1+(row.fault_factor-1)*progress;
else
    signals.fault_scale = ones(size(t));
end
end

function y = smooth_step(t,t0,t1)
x = min(max((t-t0)/(t1-t0),0),1);
y = x.^2.*(3-2*x);
end

