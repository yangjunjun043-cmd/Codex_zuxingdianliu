function [data,idealData,noise] = simulate_registry_csac_condition( ...
        row,cfg,noiseSeed)
% External structural-mismatch path. AutoComp9 remains unchanged.
caseRegistry = phase1a_case_registry();
caseInfo = caseRegistry(caseRegistry.case_name == row.anchor_case,:);
if height(caseInfo) ~= 1 || string(row.anchor_case) ~= "Case02_slow_drift"
    error('Phase2:CsACAnchor', ...
        'CsAC formal rows must use the frozen Case02 anchor.');
end
cleanCfg = cfg;
cleanCfg.SNR_dB = Inf;
[cleanData,cleanReference] = simulate_phase2_case(cleanCfg, ...
    char(caseInfo.legacy_scenario_name),caseInfo.seed);
signals = generate_coupling_signals( ...
    (0:cfg.Ts:cfg.StopTime).',char(caseInfo.legacy_scenario_name), ...
    caseInfo.seed);
[data,metadata] = generic_external_csac_wrapper(cleanData, ...
    cleanReference,row.CsAC_truth_pF,cfg.SNR_dB,noiseSeed,cfg,signals);
idealData = metadata.ideal;
noise = metadata.noise;
end

function [data,metadata] = generic_external_csac_wrapper( ...
        cleanData,cleanReference,CsACpF,snrDB,rngSeed,cfg,signals)
% This function deliberately has no CsAC==0 shortcut. Zero and nonzero
% injections traverse the identical ideal -> contribution -> sigma -> RNG
% -> noisy-current chain required by the Step 3 strengthened gate.
duA = gradient(cleanData.ua,cleanData.t);
duC = gradient(cleanData.uc,cleanData.t);
contribution = CsACpF*1e-12*(duA-duC);
ideal = cleanData;
ideal.ia = cleanData.ia+contribution;
ideal.ib = cleanData.ib+zeros(size(contribution));
ideal.ic = cleanData.ic-contribution;
noiseBasis = cleanReference;
noiseBasis.ia = cleanReference.ia+contribution;
noiseBasis.ib = cleanReference.ib+zeros(size(contribution));
noiseBasis.ic = cleanReference.ic-contribution;
sigma = struct( ...
    'A',rms(noiseBasis.ia)/10^(snrDB/20), ...
    'B',rms(noiseBasis.ib)/10^(snrDB/20), ...
    'C',rms(noiseBasis.ic)/10^(snrDB/20));
rng(rngSeed);
noise = struct( ...
    'A',sigma.A*randn(size(ideal.ia)), ...
    'B',sigma.B*randn(size(ideal.ib)), ...
    'C',sigma.C*randn(size(ideal.ic)));
% Route the structural contribution and newly generated noise through the
% existing additive current inputs. This preserves the model's floating-
% point operation path while keeping the injection external to AutoComp9.
data = run_once(cfg,signals,contribution+noise.A,noise.B, ...
    -contribution+noise.C);
for name = ["Ca","Cb","Cc"]
    data.(char(name)) = cfg.Cself_pF*ones(size(data.t));
end
data.CsAC_pF = CsACpF*ones(size(data.t));
ideal.CsAC_pF = data.CsAC_pF;
data.scenario = "phase2_registry_csac";
ideal.scenario = "phase2_registry_csac_ideal";
data.current_source = "phase2_external_csac_generic_path";
ideal.current_source = "phase2_external_csac_generic_path_ideal";
metadata = struct('ideal',ideal,'noise_basis',noiseBasis, ...
    'noise',noise,'sigma',sigma,'duA',duA,'duC',duC, ...
    'contribution',contribution,'rng_seed',rngSeed, ...
    'injection_order', ...
    "ideal current -> CsAC contribution -> noise sigma -> noise");
end

function data = run_once(cfg,signals,noiseA,noiseB,noiseC)
in = Simulink.SimulationInput(cfg.model);
vars = struct('StopTime',cfg.StopTime,'h3_ratio',cfg.h3_ratio, ...
    'phi3_deg',cfg.phi3_deg,'Vneg_pu',cfg.Vneg_pu,'f',cfg.f, ...
    'Un_LL',cfg.Un_LL,'C0',cfg.C0,'C_moa',cfg.C_moa, ...
    'C1',cfg.C1,'C2',cfg.C2,'Vref_moa',cfg.moa_Vref_V, ...
    'Iref_moa',cfg.moa_Iref_A,'alpha_moa',cfg.moa_alpha, ...
    'Ts',cfg.Ts,'Ts_model',cfg.Ts,'Cself_pF',cfg.Cself_pF, ...
    'Ccoupling_disabled_F',1e-18);
names = fieldnames(vars);
for k = 1:numel(names)
    in = in.setVariable(names{k},vars.(names{k}));
end
dataset = Simulink.SimulationData.Dataset;
dataset{1} = timeseries(signals.Cs1_pF,signals.t);
dataset{2} = timeseries(signals.Cs2_pF,signals.t);
dataset{3} = timeseries(signals.fault_scale,signals.t);
dataset{4} = timeseries(noiseA,signals.t);
dataset{5} = timeseries(noiseB,signals.t);
dataset{6} = timeseries(noiseC,signals.t);
in = in.setExternalInput(dataset);
in = in.setModelParameter('StopTime',num2str(cfg.StopTime));
out = sim(in);
[data.t,data.ua] = read_signal(out,'uA');
[~,data.ub] = read_signal(out,'uB');
[~,data.uc] = read_signal(out,'uC');
[~,data.ia] = read_signal(out,'iA_total');
[~,data.ib] = read_signal(out,'iB_total');
[~,data.ic] = read_signal(out,'iC_total');
[~,data.irA] = read_signal(out,'iA_R_true');
[~,data.irB] = read_signal(out,'iB_R_true');
[~,data.irC] = read_signal(out,'iC_R_true');
[~,data.Cs1] = read_signal(out,'Cs1_true');
[~,data.Cs2] = read_signal(out,'Cs2_true');
end

function noise = noise_for_snr(x,snrDB)
if isfinite(snrDB)
    noise = rms(x)/10^(snrDB/20)*randn(size(x));
else
    noise = zeros(size(x));
end
end

function [t,x] = read_signal(out,name)
s = out.get(name);
if isa(s,'timeseries')
    t = s.Time; x = s.Data;
else
    t = s.time; x = s.signals.values;
end
t = t(:); x = squeeze(x); x = x(:);
end

function pass = mapping_audit(row,physicalCfg,algorithmCfg,signals, ...
        data,cleanData,noise,ref)
tol = 1e-9;
pass = ...
    numeric_scalar_equal(physicalCfg.SNR_dB,row.SNR_dB,tol) && ...
    abs(physicalCfg.h3_ratio-row.h3_ratio) <= tol && ...
    abs(physicalCfg.phi3_deg-row.h3_phase_deg) <= tol && ...
    abs(physicalCfg.Vneg_pu-row.negative_sequence_pu) <= tol && ...
    abs(physicalCfg.Cself_pF-row.Cself_truth_pF) <= tol && ...
    abs(algorithmCfg.Cself_pF-row.Cself_algorithm_pF) <= tol && ...
    abs(algorithmCfg.phase_error_deg- ...
        row.reference_phase_error_deg) <= tol && ...
    abs(signals.Cs1_pF(1)-row.Cs1_initial_pF) <= tol && ...
    abs(signals.Cs2_pF(1)-row.Cs2_initial_pF) <= tol && ...
    max(abs(data.Cs1-signals.Cs1_pF)) <= tol && ...
    max(abs(data.Cs2-signals.Cs2_pF)) <= tol && ...
    all(isfinite([noise.A;noise.B;noise.C]));
if string(row.experiment_group) == "CSAC_MISMATCH"
    pass = pass && isfield(data,'CsAC_pF') && ...
        max(abs(data.CsAC_pF-row.CsAC_truth_pF)) <= tol;
end
if isfinite(row.Cs1_final_pF)
    pass = pass && abs(signals.Cs1_pF(end)-row.Cs1_final_pF) <= tol;
end
if isfinite(row.Cs2_final_pF)
    pass = pass && abs(signals.Cs2_pF(end)-row.Cs2_final_pF) <= tol;
end
if string(row.fault_mode) == "PERSISTENT_B_RESISTIVE"
    pass = pass && abs(max(signals.fault_scale)-row.fault_factor) <= tol && ...
        all(signals.fault_scale(signals.t < row.fault_start_s) == 1);
else
    pass = pass && all(signals.fault_scale == 1);
end
zeroRef = reconstruct_refs_from_b(data.t,data.ub,algorithmCfg.f, ...
    algorithmCfg.init_start,algorithmCfg.init_end,0);
phase1Delta = wrap_to_180(rad2deg(ref.phi1-zeroRef.phi1));
phase3Delta = wrap_to_180(rad2deg(ref.phi3-zeroRef.phi3));
pass = pass && abs(phase1Delta-row.reference_phase_error_deg) < 1e-10 && ...
    abs(phase3Delta-3*row.reference_phase_error_deg) < 1e-10;
if string(row.experiment_group) == "THIRD_HARMONIC"
    [fundamental,third] = voltage_harmonics(data.t,data.ub,physicalCfg.f);
    pass = pass && abs(third/fundamental-row.h3_ratio) < 1e-8;
end
if string(row.experiment_group) == "NEGATIVE_SEQUENCE"
    balancedMismatch = rms(data.ua-zeroRef.ua)+rms(data.uc-zeroRef.uc);
    pass = pass && row.negative_sequence_pu > 0 && ...
        balancedMismatch > 1e-6 && ...
        string(row.negative_sequence_convention_status) == ...
        "UNRESOLVED_INTERNAL_CONVENTION" && ...
        string(row.interpretation_flag) == ...
        "CONFIGURED_VALIDITY_BOUNDARY_ONLY";
end
pass = pass && max(abs((data.ia-cleanData.ia)-noise.A)) < 1e-12 && ...
    max(abs((data.ib-cleanData.ib)-noise.B)) < 1e-12 && ...
