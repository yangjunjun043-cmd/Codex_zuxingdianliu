function metrics = extract_frozen_metrics(mode,result,counterfactual, ...
        data,cfg,windows,isFault)
metricIndex = data.t >= windows.metric_start_s & ...
    data.t < windows.metric_end_s;
legacy = evaluate_case_metrics(data,result.ir,result.cHist, ...
    mode,"Phase2_registry",cfg);
metrics = struct( ...
    'Cs1_RMSE_pF',sqrt(mean((result.cHist(metricIndex,1)- ...
        data.Cs1(metricIndex)).^2)), ...
    'Cs2_RMSE_pF',sqrt(mean((result.cHist(metricIndex,2)- ...
        data.Cs2(metricIndex)).^2)), ...
    'Cs1_max_abs_error_pF',max(abs(result.cHist(metricIndex,1)- ...
        data.Cs1(metricIndex))), ...
    'Cs2_max_abs_error_pF',max(abs(result.cHist(metricIndex,2)- ...
        data.Cs2(metricIndex))), ...
    'B_resistive_fundamental_error_pct',legacy.B_FundErr_pct, ...
    'fault_factor_true',NaN,'fault_factor_est',NaN, ...
    'fault_retention_error_pct',NaN, ...
    'DeltaCs1_fault_induced_pF',NaN, ...
    'DeltaCs2_fault_induced_pF',NaN, ...
    'Cs_fault_induced_bias_norm_pF',NaN, ...
    'hard_gate_active_ratio',NaN,'hard_gate_latency_s',NaN, ...
    'mean_update_weight',NaN, ...
    'unnecessary_suppression_ratio',NaN, ...
    'information_suppression_ratio_J',NaN, ...
    'information_suppression_ratio_h',NaN);
if isFault
    pre = data.t >= windows.pre_start_s & data.t < windows.pre_end_s;
    post = data.t >= windows.fault_start_s & data.t < windows.fault_end_s;
    metrics.fault_factor_true = fault_factor( ...
        data.t,data.irB,pre,post,cfg.f);
    metrics.fault_factor_est = fault_factor( ...
        data.t,result.ir.B,pre,post,cfg.f);
    metrics.fault_retention_error_pct = ...
        (metrics.fault_factor_est-metrics.fault_factor_true)/ ...
        metrics.fault_factor_true*100;
    actualChange = parameter_change(result.cHist,pre,post);
    cfChange = parameter_change(counterfactual.cHist,pre,post);
    induced = actualChange-cfChange;
    metrics.DeltaCs1_fault_induced_pF = induced(1);
    metrics.DeltaCs2_fault_induced_pF = induced(2);
    metrics.Cs_fault_induced_bias_norm_pF = hypot(induced(1),induced(2));
end
if mode == "M3"
    cycle = result.tracker.cycle;
    active = cycle.gate > 0;
    if isFault
        response = cycle.time_s >= windows.response_start_s;
    else
        response = true(height(cycle),1);
    end
    metrics.hard_gate_active_ratio = mean(active(response));
    first = find(active & response,1,'first');
    if ~isempty(first) && isFault
        metrics.hard_gate_latency_s = ...
            cycle.time_s(first)-windows.response_start_s;
    end
elseif mode == "M4"
    cycle = result.tracker.cycle;
    if isFault
        samplesPerCycle = round((1/median(diff(data.t)))/cfg.f);
        cycleStart = cycle.time_s-(samplesPerCycle-1)*median(diff(data.t));
        index = cycleStart >= windows.fault_start_s & ...
            cycle.time_s < windows.fault_end_s;
        metrics.mean_update_weight = mean(cycle.update_weight(index));
        [metrics.information_suppression_ratio_J, ...
            metrics.information_suppression_ratio_h] = ...
            information_suppression_ratios(cycle,index);
    else
        metrics.mean_update_weight = mean(cycle.update_weight);
        metrics.unnecessary_suppression_ratio = ...
            mean(1-cycle.update_weight);
    end
end
end

function [ratioJ,ratioH] = information_suppression_ratios(cycle,index)
jRaw = cycle{index,{'J_increment_raw_11','J_increment_raw_12', ...
    'J_increment_raw_21','J_increment_raw_22'}};
jApplied = cycle{index,{'J_increment_applied_11', ...
    'J_increment_applied_12','J_increment_applied_21', ...
    'J_increment_applied_22'}};
hRaw = cycle{index,{'h_increment_raw_1','h_increment_raw_2'}};
hApplied = cycle{index,{'h_increment_applied_1', ...
    'h_increment_applied_2'}};
ratioJ = sum(vecnorm(jRaw-jApplied,2,2))/ ...
    (sum(vecnorm(jRaw,2,2))+eps);
ratioH = sum(vecnorm(hRaw-hApplied,2,2))/ ...
    (sum(vecnorm(hRaw,2,2))+eps);
end

function change = parameter_change(cHist,pre,post)
change = mean(cHist(post,:),1)-mean(cHist(pre,:),1);
end

function value = fault_factor(t,x,pre,post,f)
value = fundamental_rms(t(post),x(post),f)/ ...
    (fundamental_rms(t(pre),x(pre),f)+eps);
end

function value = fundamental_rms(t,x,f)
w = 2*pi*f;
coefficients = [sin(w*t),cos(w*t),ones(size(t))]\x;
value = hypot(coefficients(1),coefficients(2))/sqrt(2);
end

