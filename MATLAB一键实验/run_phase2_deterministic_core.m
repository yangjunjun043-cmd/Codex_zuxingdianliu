function equal = numeric_scalar_equal(a,b,tolerance)
equal = (isinf(a) && isinf(b) && sign(a) == sign(b)) || ...
    (isfinite(a) && isfinite(b) && abs(a-b) <= tolerance);
end

function [fundamental,third] = voltage_harmonics(t,x,f)
w = 2*pi*f;
index = t >= 0.1 & t < 0.7;
matrix = [sin(w*t(index)),cos(w*t(index)), ...
    sin(3*w*t(index)),cos(3*w*t(index)),ones(nnz(index),1)];
beta = matrix\x(index);
fundamental = hypot(beta(1),beta(2));
third = hypot(beta(3),beta(4));
end

