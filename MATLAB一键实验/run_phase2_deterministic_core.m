function output = run_phase2_deterministic_core(action,conditionId)
%RUN_PHASE2_DETERMINISTIC_CORE Phase 2 registry-driven deterministic runner.
% Public entries:
%   run_phase2_deterministic_core("run_condition","P2_FA_FO_130")
%   run_phase2_deterministic_core("smoke_validation")
%   run_phase2_deterministic_core("model_mismatch")
%
% Step 2B-1 is validation only. The six-condition smoke set is deliberately
% fixed here; every physical factor level is read from the frozen registry.

if nargin < 1 || isempty(action)
    action = "smoke_validation";
end
action = lower(strtrim(string(action)));
if ~isscalar(action)
    error('Phase2:RunnerAction','Action must be a scalar string.');
end

paths = runner_paths();
addpath(paths.matlab_root);
conditionRegistry = read_registry(paths.condition_registry);
executionRegistry = read_registry(paths.execution_registry);

if action == "generic_zero_path_regression"
    authorization = step2a_authorization(paths.step2a_report);
    pre = capture_frozen_integrity(paths);
    if ~pre.pass || ~authorization.source || ~authorization.csac
        error('Phase2:GenericZeroAuthorization', ...
            'Frozen integrity or Step 2A CsAC authorization failed.');
    end
    output = generic_zero_path_regression(paths);
    post = capture_frozen_integrity(paths);
    output.frozen_integrity_pass = pre.pass && post.pass && ...
        isequal(pre.actual_sha256,post.actual_sha256);
    if ~output.frozen_integrity_pass
        error('Phase2:FrozenIntegrity', ...
            'Frozen hashes changed during generic zero-path regression.');
    end
    fprintf('GENERIC_ZERO_PATH_REGRESSION=%s\n',pass_fail(output.pass));
    return
elseif action == "model_mismatch"
    output = run_model_mismatch( ...
        paths,conditionRegistry,executionRegistry);
    return
elseif action == "full_deterministic_core"
    output = run_full_deterministic_core( ...
        paths,conditionRegistry,executionRegistry);
    return
elseif action == "run_condition"
    if nargin < 2
        error('Phase2:ConditionRequired', ...
            'run_condition requires one condition_id.');
    end
    pre = capture_frozen_integrity(paths);
    if ~pre.pass
        error('Phase2:FrozenIntegrity', ...
            'PRE frozen integrity failed; execution is blocked.');
    end
    run = execute_condition(conditionRegistry, ...
        executionRegistry,string(conditionId));
    post = capture_frozen_integrity(paths);
    run.frozen_integrity = struct('pre',pre,'post',post, ...
        'unchanged',pre.pass && post.pass && ...
        isequal(pre.actual_sha256,post.actual_sha256));
    if ~run.frozen_integrity.unchanged
        error('Phase2:FrozenIntegrity', ...
            'POST frozen integrity failed or frozen hashes changed.');
    end
    run.rows.frozen_integrity_pass(:) = true;
    output = run;
    return
elseif action ~= "smoke_validation"
    error('Phase2:RunnerAction','Unsupported action: %s.',action);
end

if ~isfolder(paths.output_root)
    mkdir(paths.output_root);
end
smokeIds = ["P2_FA_FO_130";"P2_FA_DF_130";"P2_SN_20"; ...
    "P2_PE_100";"P2_H3_100";"P2_NS_003"];
pre = capture_frozen_integrity(paths);
allRows = empty_result_table();

if pre.pass
    for k = 1:numel(smokeIds)
        try
            currentRun = execute_condition(conditionRegistry, ...
                executionRegistry,smokeIds(k));
            allRows = [allRows;currentRun.rows]; %#ok<AGROW>
            fprintf('STEP2B1 %s: 4/4 evaluations complete.\n',smokeIds(k));
        catch exception
            allRows = [allRows;failure_rows(conditionRegistry, ...
                smokeIds(k),exception)]; %#ok<AGROW>
            fprintf(2,'STEP2B1 %s failed: %s\n', ...
                smokeIds(k),exception.message);
        end
    end
else
    exception = MException('Phase2:FrozenIntegrity', ...
        'PRE frozen integrity failed; smoke simulation was not executed.');
    for k = 1:numel(smokeIds)
        allRows = [allRows;failure_rows(conditionRegistry, ...
            smokeIds(k),exception)]; %#ok<AGROW>
    end
end

post = capture_frozen_integrity(paths);
frozenPass = pre.pass && post.pass && ...
    isequal(pre.actual_sha256,post.actual_sha256);
allRows.frozen_integrity_pass(:) = frozenPass;

main = allRows.record_type == "MAIN";
complete = main & ~allRows.numerical_failure & ...
    ~allRows.metric_missing;
conditionComplete = false(numel(smokeIds),1);
for k = 1:numel(smokeIds)
    index = main & allRows.condition_id == smokeIds(k);
    conditionComplete(k) = nnz(index) == 4 && all(complete(index));
end
runnerPass = height(allRows(main,:)) == 24 && ...
    all(allRows.registry_match(main)) && ...
    all(allRows.shared_data_pass(main)) && ...
    all(~allRows.metric_missing(main)) && ...
    all(~allRows.numerical_failure(main)) && frozenPass;

writetable(allRows,paths.results_csv);
write_report(paths,allRows,smokeIds,conditionComplete,pre,post, ...
    frozenPass,runnerPass);

output = struct( ...
    'status',status_label(runnerPass,pre.pass,frozenPass), ...
    'registry_runner_authorized',runnerPass, ...
    'smoke_conditions_complete',nnz(conditionComplete), ...
    'algorithm_evaluations_complete',nnz(complete), ...
    'frozen_source_modified',~frozenPass, ...
    'full_deterministic_matrix_executed',false, ...
    'ready_for_step2b2',runnerPass, ...
    'results_csv',string(paths.results_csv), ...
    'report',string(paths.report));

fprintf('STEP2B1_STATUS=%s\n',output.status);
fprintf('REGISTRY_RUNNER=%s\n',authorized_label(runnerPass));
fprintf('SMOKE_CONDITIONS=%d/6 COMPLETE\n',nnz(conditionComplete));
fprintf('ALGORITHM_EVALUATIONS=%d/24 COMPLETE\n',nnz(complete));
fprintf('FROZEN_SOURCE_MODIFIED=%s\n',yes_no(~frozenPass));
fprintf('FULL_DETERMINISTIC_MATRIX_EXECUTED=NO\n');
fprintf('READY_FOR_STEP2B2=%s\n',yes_no(runnerPass));
end

function output = run_full_deterministic_core( ...
        paths,conditionRegistry,executionRegistry)
groups = ["FAULT_AMPLITUDE";"SNR";"REFERENCE_PHASE"; ...
    "THIRD_HARMONIC";"NEGATIVE_SEQUENCE"];
isNew = false(height(conditionRegistry),1);
isBlocked = false(height(conditionRegistry),1);
for k = 1:height(conditionRegistry)
    isNew(k) = truthy(conditionRegistry.is_new_phase2_condition(k));
    isBlocked(k) = truthy(conditionRegistry.is_blocked(k));
end
selected = conditionRegistry.registry_kind == "DETERMINISTIC" & ...
    ismember(conditionRegistry.experiment_group,groups) & ...
    isNew & ~isBlocked;
conditions = conditionRegistry(selected,:);
if height(conditions) ~= 25 || numel(unique(conditions.condition_id)) ~= 25
    error('Phase2:FullCoreConditionCount', ...
        'Frozen registry must select exactly 25 unique new conditions.');
end
evaluationMask = ismember(executionRegistry.condition_id, ...
    conditions.condition_id) & ...
    executionRegistry.record_type == "MAIN_ALGORITHM_EVALUATION";
evaluations = executionRegistry(evaluationMask,:);
if height(evaluations) ~= 100 || ...
        any(evaluations.execution_status ~= "READY")
    error('Phase2:FullCoreEvaluationCount', ...
        'Frozen execution registry must select 100 READY evaluations.');
end

if ~isfolder(paths.step2b2_output_root)
    mkdir(paths.step2b2_output_root);
end
pre = capture_frozen_integrity(paths);
rows = empty_result_table();
conditionComplete = false(height(conditions),1);
if pre.pass
    for k = 1:height(conditions)
        conditionId = conditions.condition_id(k);
        try
            current = execute_condition(conditionRegistry, ...
                executionRegistry,conditionId);
            rows = [rows;current.rows]; %#ok<AGROW>
            conditionComplete(k) = all(~current.rows.numerical_failure & ...
                ~current.rows.metric_missing & ...
                current.rows.registry_match & ...
                current.rows.shared_data_pass) && height(current.rows) == 4;
            fprintf('STEP2B2 %02d/25 %s: %d/4 complete.\n', ...
                k,conditionId,nnz(~current.rows.numerical_failure & ...
                ~current.rows.metric_missing));
        catch exception
            rows = [rows;failure_rows(conditionRegistry, ...
                conditionId,exception)]; %#ok<AGROW>
            fprintf(2,'STEP2B2 %02d/25 %s failed: %s\n', ...
                k,conditionId,exception.message);
        end
    end
else
    exception = MException('Phase2:FrozenIntegrity', ...
        'PRE frozen integrity failed; formal batch was not executed.');
    for k = 1:height(conditions)
        rows = [rows;failure_rows(conditionRegistry, ...
            conditions.condition_id(k),exception)]; %#ok<AGROW>
    end
end

post = capture_frozen_integrity(paths);
frozenPass = pre.pass && post.pass && ...
    isequal(pre.actual_sha256,post.actual_sha256);
rows.frozen_integrity_pass(:) = frozenPass;
main = rows.record_type == "MAIN";
complete = main & ~rows.numerical_failure & ~rows.metric_missing;
batchPass = height(rows(main,:)) == 100 && ...
    nnz(conditionComplete) == 25 && ...
    all(rows.registry_match(main)) && ...
    all(rows.shared_data_pass(main)) && ...
    all(~rows.metric_missing(main)) && ...
    all(~rows.numerical_failure(main)) && frozenPass;

writetable(rows,paths.step2b2_results_csv);
write_step2b2_report(paths,rows,conditions,conditionComplete, ...
    pre,post,frozenPass,batchPass);

output = struct( ...
    'status',status_label(batchPass,pre.pass,frozenPass), ...
    'physical_conditions_complete',nnz(conditionComplete), ...
    'algorithm_evaluations_complete',nnz(complete), ...
    'numerical_failures',nnz(main & rows.numerical_failure), ...
    'metric_missing_rows',nnz(main & rows.metric_missing), ...
    'frozen_source_modified',~frozenPass, ...
    'full_deterministic_core_complete',batchPass, ...
    'ready_for_step3',batchPass, ...
    'results_csv',string(paths.step2b2_results_csv), ...
    'report',string(paths.step2b2_report));
fprintf('STEP2B2_STATUS=%s\n',output.status);
fprintf('PHYSICAL_CONDITIONS_COMPLETE=%d/25\n', ...
    output.physical_conditions_complete);
fprintf('ALGORITHM_EVALUATIONS_COMPLETE=%d/100\n', ...
    output.algorithm_evaluations_complete);
fprintf('NUMERICAL_FAILURES=%d\n',output.numerical_failures);
fprintf('METRIC_MISSING_ROWS=%d\n',output.metric_missing_rows);
fprintf('FROZEN_SOURCE_MODIFIED=%s\n', ...
    yes_no(output.frozen_source_modified));
fprintf('FULL_DETERMINISTIC_CORE_COMPLETE=%s\n',yes_no(batchPass));
fprintf('READY_FOR_STEP3=%s\n',yes_no(batchPass));
end

function output = run_model_mismatch( ...
        paths,conditionRegistry,executionRegistry)
cselfIds = ["P2_CS_M10";"P2_CS_M05";"P2_CS_M02"; ...
    "P2_CS_P02";"P2_CS_P05";"P2_CS_P10"];
csacIds = ["P2_AC_005";"P2_AC_010";"P2_AC_020";"P2_AC_030"];
assert_model_mismatch_registry(conditionRegistry,executionRegistry, ...
    cselfIds,csacIds);
authorization = step2a_authorization(paths.step2a_report);
if ~authorization.cself || ~authorization.source
    error('Phase2:Step3Authorization', ...
        'Step 2A does not authorize the Cself formal matrix.');
end
if ~isfolder(paths.step3_output_root)
    mkdir(paths.step3_output_root);
end

pre = capture_frozen_integrity(paths);
rows = empty_step3_result_table();
cselfComplete = false(numel(cselfIds),1);
csacComplete = false(numel(csacIds),1);
gate = empty_generic_gate_details();
if pre.pass
    for k = 1:numel(cselfIds)
        try
            current = execute_condition(conditionRegistry, ...
                executionRegistry,cselfIds(k),true);
            currentRows = augment_step3_rows(current.rows, ...
                current.condition_registry_row, ...
                "Step2A CSELF_SPLIT_INTERFACE_GATE authorization; "+ ...
                "frozen registry retained PENDING_GATE.");
            rows = [rows;currentRows]; %#ok<AGROW>
            cselfComplete(k) = step3_condition_complete(currentRows);
            fprintf('STEP3 CSELF %d/6 %s: %d/4 complete.\n', ...
                k,cselfIds(k),nnz(~currentRows.numerical_failure & ...
                ~currentRows.metric_missing));
        catch exception
            failed = failure_rows(conditionRegistry,cselfIds(k),exception);
            registryRow = conditionRegistry( ...
                conditionRegistry.condition_id == cselfIds(k),:);
            rows = [rows;augment_step3_rows(failed,registryRow, ...
                string(exception.identifier)+": "+ ...
                string(exception.message))]; %#ok<AGROW>
            fprintf(2,'STEP3 CSELF %s failed: %s\n', ...
                cselfIds(k),exception.message);
        end
    end

    try
        gate = generic_zero_path_regression(paths);
    catch exception
        gate = empty_generic_gate_details();
        gate.error = string(getReport(exception,'extended', ...
            'hyperlinks','off'));
        gate.pass = false;
    end
    fprintf('GENERIC_ZERO_PATH_REGRESSION=%s\n',pass_fail(gate.pass));

    if gate.pass && authorization.csac
        for k = 1:numel(csacIds)
            try
                current = execute_condition(conditionRegistry, ...
                    executionRegistry,csacIds(k),true);
                currentRows = augment_step3_rows(current.rows, ...
                    current.condition_registry_row, ...
                    "Step2A ZERO_INJECTION_REGRESSION plus Step3 "+ ...
                    "GENERIC_ZERO_PATH_REGRESSION authorization; "+ ...
                    "frozen registry retained PENDING_GATE.");
                rows = [rows;currentRows]; %#ok<AGROW>
                csacComplete(k) = step3_condition_complete(currentRows);
                fprintf('STEP3 CSAC %d/4 %s: %d/4 complete.\n', ...
                    k,csacIds(k),nnz(~currentRows.numerical_failure & ...
                    ~currentRows.metric_missing));
            catch exception
                failed = failure_rows(conditionRegistry,csacIds(k),exception);
                registryRow = conditionRegistry( ...
                    conditionRegistry.condition_id == csacIds(k),:);
                rows = [rows;augment_step3_rows(failed,registryRow, ...
                    string(exception.identifier)+": "+ ...
                    string(exception.message))]; %#ok<AGROW>
                fprintf(2,'STEP3 CSAC %s failed: %s\n', ...
                    csacIds(k),exception.message);
            end
        end
    end
else
    gate.error = "PRE frozen integrity failed; Step 3 was not executed.";
end

post = capture_frozen_integrity(paths);
frozenPass = pre.pass && post.pass && ...
    isequal(pre.actual_sha256,post.actual_sha256);
rows.frozen_integrity_pass(:) = frozenPass;
mainComplete = ~rows.numerical_failure & ~rows.metric_missing & ...
    rows.registry_match & rows.shared_data_pass;
cselfDone = nnz(cselfComplete);
csacDone = nnz(csacComplete);
if frozenPass && cselfDone == 6 && gate.pass && csacDone == 4
    status = "PASS";
elseif frozenPass && cselfDone == 6 && ~gate.pass && ...
        all(mainComplete)
    status = "PARTIAL";
else
    status = "BLOCKED";
end
readyForStep4 = frozenPass && cselfDone == 6 && ...
    all(mainComplete) && (~gate.pass || csacDone == 4);

writetable(rows,paths.step3_results_csv);
write_step3_report(paths,rows,pre,post,authorization,gate, ...
    cselfDone,csacDone,status,readyForStep4,frozenPass);
output = struct('status',status, ...
    'cself_conditions_complete',cselfDone, ...
    'cself_evaluations_complete',nnz( ...
    ismember(rows.condition_id,cselfIds) & mainComplete), ...
    'generic_zero_path_regression',gate.pass, ...
    'csac_conditions_complete',csacDone, ...
    'csac_evaluations_complete',nnz( ...
    ismember(rows.condition_id,csacIds) & mainComplete), ...
    'numerical_failures',nnz(rows.numerical_failure), ...
    'metric_missing_rows',nnz(rows.metric_missing), ...
    'frozen_source_modified',~frozenPass, ...
    'ready_for_step4',readyForStep4, ...
    'results_csv',string(paths.step3_results_csv), ...
    'report',string(paths.step3_report));
fprintf('STEP_3_STATUS=%s\n',status);
fprintf('CSELF_CONDITIONS_COMPLETE=%d/6\n',cselfDone);
fprintf('CSELF_EVALUATIONS_COMPLETE=%d/24\n', ...
    output.cself_evaluations_complete);
fprintf('GENERIC_ZERO_PATH_REGRESSION=%s\n',pass_fail(gate.pass));
fprintf('CSAC_CONDITIONS_COMPLETE=%d/4\n',csacDone);
fprintf('CSAC_EVALUATIONS_COMPLETE=%d/16\n', ...
    output.csac_evaluations_complete);
fprintf('NUMERICAL_FAILURES=%d\n',output.numerical_failures);
fprintf('FROZEN_SOURCE_MODIFIED=%s\n',yes_no(~frozenPass));
fprintf('READY_FOR_STEP4=%s\n',yes_no(readyForStep4));
end

function assert_model_mismatch_registry(registry,executionRegistry, ...
        cselfIds,csacIds)
ids = [cselfIds;csacIds];
selected = registry(ismember(registry.condition_id,ids),:);
if height(selected) ~= 10 || numel(unique(selected.condition_id)) ~= 10
    error('Phase2:Step3ConditionCount', ...
        'Frozen registry must contain exactly 10 Step 3 conditions.');
end
if nnz(selected.experiment_group == "CSELF_MISMATCH") ~= 6 || ...
        nnz(selected.experiment_group == "CSAC_MISMATCH") ~= 4
    error('Phase2:Step3GroupCount','Step 3 group cardinality mismatch.');
end
if any(arrayfun(@truthy,selected.is_blocked)) || ...
        any(selected.registry_state ~= "FROZEN")
    error('Phase2:Step3RegistryState', ...
        'Step 3 contains blocked or non-frozen conditions.');
end
evaluations = executionRegistry( ...
    ismember(executionRegistry.condition_id,ids) & ...
    executionRegistry.record_type == "MAIN_ALGORITHM_EVALUATION",:);
if height(evaluations) ~= 40 || ...
        any(evaluations.execution_status ~= "PENDING_GATE")
    error('Phase2:Step3EvaluationCount', ...
        'Expected 40 frozen PENDING_GATE evaluation rows.');
end
for id = ids.'
    modes = sort(string(evaluations.algorithm_id( ...
        evaluations.condition_id == id)));
    if ~isequal(modes,["M0";"M2";"M3";"M4"])
        error('Phase2:Step3AlgorithmSet', ...
            'Condition %s does not map to M0/M2/M3/M4.',id);
    end
end
end

function authorization = step2a_authorization(reportPath)
textValue = string(fileread(reportPath));
authorization = struct( ...
    'source',contains(textValue,"NO_FROZEN_SOURCE_DIFF_GATE: PASS"), ...
    'cself',contains(textValue,"CSELF_SPLIT_INTERFACE_GATE: PASS"), ...
    'csac',contains(textValue,"ZERO_INJECTION_REGRESSION: PASS"), ...
    'step2a',contains(textValue,"STEP 2A STATUS: PASS"));
if ~authorization.step2a
    authorization.source = false;
    authorization.cself = false;
    authorization.csac = false;
end
end

function rows = empty_step3_result_table()
rows = empty_result_table();
rows.Cself_truth_pF = zeros(0,1);
rows.Cself_algorithm_pF = zeros(0,1);
rows.Cself_mismatch_pct = zeros(0,1);
rows.CsAC_truth_pF = zeros(0,1);
end

function rows = augment_step3_rows(rows,registryRow,extraNote)
rows.Cself_truth_pF = repmat(registryRow.Cself_truth_pF,height(rows),1);
rows.Cself_algorithm_pF = repmat( ...
    registryRow.Cself_algorithm_pF,height(rows),1);
rows.Cself_mismatch_pct = repmat( ...
    registryRow.Cself_mismatch_pct,height(rows),1);
rows.CsAC_truth_pF = repmat(registryRow.CsAC_truth_pF,height(rows),1);
rows.notes = rows.notes+"; "+string(extraNote);
end

function complete = step3_condition_complete(rows)
complete = height(rows) == 4 && ...
    all(~rows.numerical_failure & ~rows.metric_missing & ...
    rows.registry_match & rows.shared_data_pass);
end

function gate = empty_generic_gate_details()
gate = struct('pass',false,'tolerance',1e-12, ...
    'truth_tolerance',1e-10,'ideal_current_max_difference_A',NaN, ...
    'noisy_current_max_difference_A',NaN, ...
    'reference_max_difference',NaN, ...
    'truth_max_difference',NaN, ...
    'M0_output_max_difference',NaN, ...
    'M2_output_max_difference',NaN, ...
    'M3_output_max_difference',NaN, ...
    'M4_output_max_difference',NaN, ...
    'injection_order', ...
    "ideal current -> CsAC contribution -> noise sigma -> noise", ...
    'shortcut_used',false,'error',"");
end

function gate = generic_zero_path_regression(~)
gate = empty_generic_gate_details();
request = struct('case_name',"Case02_slow_drift", ...
    'Cself_truth_pF',400,'Cself_algorithm_pF',400, ...
    'CsAC_pF',0,'algorithms',["M0" "M2" "M3" "M4"]);
nominal = run_phase2_gate_validation("execute",request);
cfg = patent_default_config();
cfg.model = 'AI6109_MOA_AutoComp9';
cfg.SNR_dB = Inf;
caseRegistry = phase1a_case_registry();
caseInfo = caseRegistry(caseRegistry.case_name == ...
    "Case02_slow_drift",:);
[cleanData,cleanReference] = simulate_phase2_case(cfg, ...
    char(caseInfo.legacy_scenario_name),caseInfo.seed);
signals = generate_coupling_signals( ...
    (0:cfg.Ts:cfg.StopTime).',char(caseInfo.legacy_scenario_name), ...
    caseInfo.seed);
[genericData,metadata] = generic_external_csac_wrapper( ...
    cleanData,cleanReference,0,30,caseInfo.seed+10000,cfg,signals);
ref = reconstruct_refs_from_b(genericData.t,genericData.ub,cfg.f, ...
    cfg.init_start,cfg.init_end,cfg.phase_error_deg);
genericResults = struct();
for mode = ["M0" "M2" "M3" "M4"]
    genericResults.(char(mode)) = run_phase1a_algorithm(mode, ...
        genericData,ref,cfg,repmat(400,1,3));
end
gate.ideal_current_max_difference_A = max(abs([ ...
    metadata.ideal.ia-cleanData.ia; ...
    metadata.ideal.ib-cleanData.ib; ...
    metadata.ideal.ic-cleanData.ic]));
gate.noisy_current_max_difference_A = max(abs([ ...
    genericData.ia-nominal.data.ia; ...
    genericData.ib-nominal.data.ib; ...
    genericData.ic-nominal.data.ic]));
gate.reference_max_difference = max_struct_numeric_difference( ...
    ref,nominal.ref,{'ua','ub','uc','dua','dub','duc', ...
    'A1','A3','phi1','phi3'});
gate.truth_max_difference = max_struct_numeric_difference( ...
    genericData,nominal.data,{'irA','irB','irC','Cs1','Cs2', ...
    'Ca','Cb','Cc'});
for mode = ["M0" "M2" "M3" "M4"]
    gate.(char(mode+"_output_max_difference")) = ...
        algorithm_output_max_difference( ...
        genericResults.(char(mode)),nominal.results.(char(mode)));
end
outputDiffs = [gate.M0_output_max_difference, ...
    gate.M2_output_max_difference,gate.M3_output_max_difference, ...
    gate.M4_output_max_difference];
gate.pass = gate.ideal_current_max_difference_A <= gate.tolerance && ...
    gate.noisy_current_max_difference_A <= gate.tolerance && ...
    gate.reference_max_difference <= gate.tolerance && ...
    gate.truth_max_difference <= gate.truth_tolerance && ...
    all(outputDiffs <= gate.tolerance);
end

function difference = algorithm_output_max_difference(a,b)
difference = max(abs(a.cHist-b.cHist),[],'all');
difference = max(difference,max(abs(a.ir.A-b.ir.A),[],'all'));
difference = max(difference,max(abs(a.ir.B-b.ir.B),[],'all'));
difference = max(difference,max(abs(a.ir.C-b.ir.C),[],'all'));
if isfield(a,'tracker') && isfield(b,'tracker') && ...
        isfield(a.tracker,'cycle') && isfield(b.tracker,'cycle')
    names = intersect(a.tracker.cycle.Properties.VariableNames, ...
        b.tracker.cycle.Properties.VariableNames,'stable');
    for k = 1:numel(names)
        av = a.tracker.cycle.(names{k});
        bv = b.tracker.cycle.(names{k});
        if isnumeric(av) && isnumeric(bv) && isequal(size(av),size(bv))
            difference = max(difference,max(abs(av-bv),[],'all'));
        end
    end
end
end

function difference = max_struct_numeric_difference(a,b,names)
difference = 0;
for k = 1:numel(names)
