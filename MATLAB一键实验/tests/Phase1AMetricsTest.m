        end

        function testM3MissingGateLogErrors(testCase)
            [caseInfo,result,data,cfg,metadata] = ...
                Phase1AMetricsTest.fixture("Case05_fault_only","M3");
            result.tracker = struct();

            testCase.verifyError(@() evaluate_phase1a_metrics( ...
                caseInfo,result,data,cfg,metadata), ...
                'Phase1A:MissingGateLog');
        end

        function testEvaluationLayerDoesNotCallSimulationOrAlgorithms(testCase)
            source = fileread(which('evaluate_phase1a_metrics'));
            forbiddenCalls = [ ...
                'track_coupling_cvff_rls\s*\(|' ...
                'initial_coupling_estimate\s*\(|' ...
                'generate_coupling_signals\s*\(|' ...
                'simulate_phase2_case\s*\(|' ...
                '\<sim\s*\('];

            testCase.verifyEmpty(regexp(source,forbiddenCalls,'once'));
        end
    end

    methods (Static, Access=private)
        function [caseInfo,result,data,cfg,metadata] = fixture(caseName,mode)
            cfg = struct('metric_start',0.8,'f',50);
            t = (0:1e-3:4).';
            w = 2*pi*cfg.f;
            trueScale = 1+0.6*(t>=3.0);
            estimatedScale = 1+0.4*(t>=3.0);
            irA = sin(w*t+2*pi/3);
            irC = sin(w*t-2*pi/3);
            data = struct( ...
                't',t, ...
                'Cs1',10*ones(size(t)), ...
                'Cs2',10*ones(size(t)), ...
                'irA',irA, ...
                'irB',trueScale.*sin(w*t), ...
                'irC',irC);
            cHist = [10*ones(size(t)),10*ones(size(t))];
            cHist(t>=3.0,1) = 15;
            cHist(t>=3.0,2) = 5;
            ir = struct('A',irA, ...
                'B',estimatedScale.*sin(w*t),'C',irC);
            tracker = struct();
            if mode == "M3"
                tracker.cycle = table([1;2],[0;0], ...
                    'VariableNames',{'time_s','gate'});
            end
            result = struct('algorithm_mode',mode,'cHist',cHist, ...
                'ir',ir,'tracker',tracker);
            caseInfo = Phase1AMetricsTest.caseInfo(caseName);
            metadata = struct( ...
                'model_sha256',"TEST_SHA256", ...
                'run_timestamp',"2026-09-17T00:00:00+08:00", ...
                'git_commit',"TEST_COMMIT", ...
                'git_branch',"main", ...
                'git_dirty_status',"TEST");
        end

        function info = caseInfo(caseName)
            registry = phase1a_case_registry();
            match = registry.case_name == caseName;
            if any(match)
                info = table2struct(registry(match,:));
            else
                info = struct('case_name',caseName,'seed',999, ...
                    'model',"AI6109_MOA_AutoComp9.slx");
            end
        end

        function cycle = activeGateLog()
            cycle = table([1.00;3.06;3.08;3.10;3.14], ...
                [0;1;1;0;1], ...
                'VariableNames',{'time_s','gate'});
        end

        function verifyGateNaN(testCase,metrics)
            values = metrics{1,{ ...
                'first_gate_trigger_s','gate_duration_cycles', ...
                'gate_duration_s'}};
            testCase.verifyTrue(all(isnan(values)));
        end
    end
end
