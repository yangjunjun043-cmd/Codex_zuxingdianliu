    methods (Test)
        function testProjectorIdentities(testCase)
            result = m5_directional_update([1;2],0.5,"directional");
            tolerance = 1e-14;

            testCase.verifyEqual(result.P_f.',result.P_f, ...
                'AbsTol',tolerance);
            testCase.verifyEqual(result.P_perp.',result.P_perp, ...
                'AbsTol',tolerance);
            testCase.verifyEqual(result.P_f*result.P_f,result.P_f, ...
                'AbsTol',tolerance);
            testCase.verifyEqual( ...
                result.P_perp*result.P_perp,result.P_perp, ...
                'AbsTol',tolerance);
            testCase.verifyEqual(result.P_f*result.P_perp,zeros(2), ...
                'AbsTol',tolerance);
            testCase.verifyEqual(result.P_f+result.P_perp,eye(2), ...
                'AbsTol',tolerance);
            testCase.verifyEqual( ...
                result.P_f*result.fault_direction, ...
                result.fault_direction,'AbsTol',tolerance);
            testCase.verifyEqual( ...
                result.P_perp*result.fault_direction,zeros(2,1), ...
                'AbsTol',tolerance);
        end

        function testWeightOneEndpoint(testCase)
            deltaRaw = [1.7;-0.4];
            result = m5_directional_update( ...
                deltaRaw,1,"directional");

            testCase.verifyEqual(result.operator,eye(2),'AbsTol',1e-14);
            testCase.verifyEqual( ...
                result.delta_protected,deltaRaw,'AbsTol',1e-14);
        end

        function testWeightZeroEndpoint(testCase)
            deltaRaw = [1.7;-0.4];
            result = m5_directional_update( ...
                deltaRaw,0,"directional");

            testCase.verifyEqual( ...
                result.P_f*result.delta_protected,zeros(2,1), ...
                'AbsTol',1e-14);
            testCase.verifyEqual( ...
                result.P_perp*result.delta_protected,result.delta_perp, ...
                'AbsTol',1e-14);
        end

        function testIntermediateWeight(testCase,intermediateWeight)
            deltaRaw = [1.7;-0.4];
            result = m5_directional_update( ...
                deltaRaw,intermediateWeight,"directional");

            testCase.verifyEqual( ...
                norm(result.P_f*result.delta_protected), ...
                intermediateWeight*result.parallel_norm, ...
                'RelTol',1e-12,'AbsTol',1e-14);
            testCase.verifyEqual( ...
                result.P_perp*result.delta_protected,result.delta_perp, ...
                'AbsTol',1e-14);
        end

        function testMatchedControlsForParallelInput(testCase)
            direction = [1;-1]/sqrt(2);
            deltaRaw = 3*direction;
            directional = m5_directional_update( ...
                deltaRaw,0.37,"directional");
            globalControl = m5_directional_update( ...
                deltaRaw,0.37,"global");

            testCase.verifyEqual( ...
                directional.delta_protected, ...
                globalControl.delta_protected,'AbsTol',1e-14);
        end

        function testMatchedControlsForPerpendicularInput(testCase)
            deltaRaw = [1;1]/sqrt(2);
            directional = m5_directional_update( ...
                deltaRaw,0.37,"directional");
            globalControl = m5_directional_update( ...
                deltaRaw,0.37,"global");

            testCase.verifyEqual( ...
                directional.delta_protected,deltaRaw,'AbsTol',1e-14);
            testCase.verifyEqual( ...
                globalControl.delta_protected,0.37*deltaRaw, ...
                'AbsTol',1e-14);
        end

        function testInformationStateReconciliation(testCase)
            regularization = 1e-10;
            JStar = [3,0.5;0.5,2];
            thetaPrevious = [0.2;-0.1];
            hStar = [2;-1];
            thetaRaw = (JStar+regularization*eye(2))\hStar;
            update = m5_directional_update( ...
                thetaRaw-thetaPrevious,0.37,"directional");
            thetaDirectional = thetaPrevious+update.delta_protected;
            hReconciled = (JStar+regularization*eye(2))*thetaDirectional;
            thetaSolveback = ...
                (JStar+regularization*eye(2))\hReconciled;

            testCase.verifyEqual( ...
                thetaSolveback,thetaDirectional, ...
                'RelTol',1e-12,'AbsTol',1e-14);
            testCase.verifyEqual( ...
                hReconciled-(JStar+regularization*eye(2))* ...
                thetaDirectional,zeros(2,1),'AbsTol',1e-14);
        end

        function testTrackerWeightOneReproducesM2(testCase)
            [data,ref,cfg,selfPF] = M5DirectionalUpdateTest.fixtureData();
            m2 = track_coupling_cvff_rls(data,ref,cfg,selfPF,false);
            options = struct('forced_selected_weight',1);
            m5 = track_coupling_m5_directional_rls( ...
                data,ref,cfg,selfPF,"M5_FULL",options);

            testCase.verifyEqual(m5.hist,m2.hist,'AbsTol',1e-12);
            testCase.verifyEqual( ...
                m5.cycle.h_reconciled_1,m5.cycle.h_star_1, ...
                'RelTol',5e-14,'AbsTol',1e-18);
            testCase.verifyEqual( ...
                m5.cycle.h_reconciled_2,m5.cycle.h_star_2, ...
                'RelTol',5e-14,'AbsTol',1e-18);
            testCase.verifyLessThanOrEqual( ...
                max(m5.cycle.solveback_error_norm),1e-12);
        end

        function testTrackerWeightZeroRemovesParallelComponent(testCase)
            [data,ref,cfg,selfPF] = M5DirectionalUpdateTest.fixtureData();
            options = struct('forced_selected_weight',0);
            result = track_coupling_m5_directional_rls( ...
                data,ref,cfg,selfPF,"M5_FULL",options);
            faultProjector = 0.5*[1,-1;-1,1];
            perpendicularProjector = eye(2)-faultProjector;
            protected = [result.cycle.delta_protected_Cs1.'; ...
                result.cycle.delta_protected_Cs2.'];
            rawPerpendicular = [result.cycle.delta_perp_Cs1.'; ...
                result.cycle.delta_perp_Cs2.'];

            testCase.verifyEqual( ...
                faultProjector*protected,zeros(size(protected)), ...
                'AbsTol',1e-12);
            testCase.verifyEqual( ...
                perpendicularProjector*protected,rawPerpendicular, ...
                'AbsTol',1e-12);
            testCase.verifyLessThanOrEqual( ...
                max(result.cycle.reconciliation_residual_norm),1e-12);
        end

