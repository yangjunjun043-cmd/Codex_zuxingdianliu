        function hashes = frozenHashes()
            root = fileparts(fileparts(mfilename('fullpath')));
            names = [ ...
                "track_coupling_cvff_rls.m"
                "track_coupling_cvff_rls.m"
                "track_coupling_m4_weighted_rls.m"
                "m4_fault_evidence.m"
                "coupling_regressor.m"
                "run_phase1a_algorithm.m"];
            hashes = strings(size(names));
            for k = 1:numel(names)
                hashes(k) = M5DirectionalUpdateTest.fileSha256( ...
                    fullfile(root,names(k)));
            end
        end

        function hash = fileSha256(path)
            fileId = fopen(path,'rb');
            if fileId < 0
                error('M5:HashFailure','Unable to hash %s.',path);
            end
            cleanup = onCleanup(@() fclose(fileId));
            bytes = fread(fileId,Inf,'*uint8');
            digester = java.security.MessageDigest.getInstance('SHA-256');
            digester.update(bytes);
            hashBytes = typecast(digester.digest(),'uint8');
            hash = upper(string(reshape(dec2hex(hashBytes,2).',1,[])));
        end
