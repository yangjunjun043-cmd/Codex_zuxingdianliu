    methods (Test)
        function testForcedOneReproducesM2(testCase)
            [data,ref,cfg,selfPF] = ...
                M4WeightedInformationUpdateTest.fixtureData();
            m2 = track_coupling_cvff_rls(data,ref,cfg,selfPF,false);
            m4 = track_coupling_m4_weighted_rls( ...
                data,ref,cfg,selfPF,struct('forced_update_weight',1));
            reference = M4WeightedInformationUpdateTest.m2StateReference( ...
                data,ref,cfg,selfPF);
            irM2 = extract_resistive_current(data,ref,selfPF,m2.hist);
            irM4 = extract_resistive_current(data,ref,selfPF,m4.hist);

            testCase.verifyEqual(m4.hist,m2.hist,'AbsTol',1e-12);
            testCase.verifyEqual(m4.cycle.Cs1_pF,m2.cycle.Cs1_pF, ...
                'AbsTol',1e-12);
            testCase.verifyEqual(m4.cycle.Cs2_pF,m2.cycle.Cs2_pF, ...
                'AbsTol',1e-12);
            testCase.verifyEqual(m4.cycle.lambda,m2.cycle.lambda, ...
                'AbsTol',1e-15);
            testCase.verifyEqual(m4.cycle.base_in,m2.cycle.base_in, ...
                'AbsTol',1e-15);
            testCase.verifyEqual(m4.cycle{:,{'J_11','J_12','J_21','J_22'}}, ...
                reference{:,{'J_11','J_12','J_21','J_22'}}, ...
                'RelTol',5e-14,'AbsTol',1e-18);
            testCase.verifyEqual(m4.cycle{:,{'h_1','h_2'}}, ...
                reference{:,{'h_1','h_2'}}, ...
                'RelTol',5e-14,'AbsTol',1e-18);
            testCase.verifyEqual(m4.cycle.rate_limit_active, ...
                reference.rate_limit_active);
            testCase.verifyEqual(m4.cycle.projection_active, ...
                reference.projection_active);
            testCase.verifyEqual(irM4.A,irM2.A,'AbsTol',1e-15);
            testCase.verifyEqual(irM4.B,irM2.B,'AbsTol',1e-15);
            testCase.verifyEqual(irM4.C,irM2.C,'AbsTol',1e-15);
        end

