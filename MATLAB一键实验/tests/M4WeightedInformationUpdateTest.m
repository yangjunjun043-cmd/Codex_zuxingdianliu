                repmat(reshape(result.initial_state.J.',1,4), ...
                height(result.cycle),1),'AbsTol',0);
            testCase.verifyEqual(result.cycle{:,{'h_1','h_2'}}, ...
                repmat(result.initial_state.h(:).',height(result.cycle),1), ...
                'AbsTol',0);
            testCase.verifyEqual(diff(result.cycle.base_in), ...
                zeros(height(result.cycle)-1,1),'AbsTol',0);
            testCase.verifyEqual(result.cycle.delta_c_applied_1, ...
                zeros(height(result.cycle),1),'AbsTol',0);
            testCase.verifyEqual(result.cycle.delta_c_applied_2, ...
                zeros(height(result.cycle),1),'AbsTol',0);
