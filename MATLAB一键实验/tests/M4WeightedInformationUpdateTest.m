    methods (Static, Access=private)
        function [data,ref,cfg,selfPF] = fixtureData()
            cfg = patent_default_config();
            cfg.Ts = 2e-4;
            cfg.StopTime = 1.2;
            cfg.SNR_dB = Inf;
            time = (0:cfg.Ts:cfg.StopTime).';
            omega = 2*pi*cfg.f;
            voltageAmplitude = sqrt(2)*cfg.Uph;
            phase = [2*pi/3,0,-2*pi/3];
            ref = struct( ...
                'ua',voltageAmplitude*sin(omega*time+phase(1)), ...
                'ub',voltageAmplitude*sin(omega*time+phase(2)), ...
                'uc',voltageAmplitude*sin(omega*time+phase(3)), ...
                'dua',omega*voltageAmplitude*cos(omega*time+phase(1)), ...
                'dub',omega*voltageAmplitude*cos(omega*time+phase(2)), ...
                'duc',omega*voltageAmplitude*cos(omega*time+phase(3)), ...
                'phi1',0,'phi3',0);
            selfPF = repmat(cfg.Cself_pF,1,3);
            coupling = [12;8];
            resistiveAmplitude = sqrt(2)*cfg.moa_Iref_A;
            irA = resistiveAmplitude*sin(omega*time+phase(1));
            irB = resistiveAmplitude*sin(omega*time+phase(2));
            irC = resistiveAmplitude*sin(omega*time+phase(3));
            ia = selfPF(1)*1e-12.*ref.dua+ ...
                coupling(1)*1e-12.*(ref.dua-ref.dub)+irA;
            ib = selfPF(2)*1e-12.*ref.dub+ ...
                coupling(1)*1e-12.*(ref.dub-ref.dua)+ ...
                coupling(2)*1e-12.*(ref.dub-ref.duc)+irB;
            ic = selfPF(3)*1e-12.*ref.duc+ ...
                coupling(2)*1e-12.*(ref.duc-ref.dub)+irC;
            data = struct('t',time,'ia',ia,'ib',ib,'ic',ic);
        end

        function reference = m2StateReference(data,ref,cfg,selfPF)
            time = data.t;
            sampleRate = 1/median(diff(time));
            samplesPerCycle = round(sampleRate/cfg.f);
            c = initial_coupling_estimate(data,ref,cfg,selfPF);
            initializationIndex = ...
                time >= cfg.init_start & time < cfg.init_end;
            [X0,~] = coupling_regressor( ...
                data,ref,initializationIndex,selfPF);
            J = 0.05*(X0'*X0)+1e-8*eye(2);
            h = J*c;
            baseIn = NaN;
            rows = struct([]);
            startIndex = find(time >= cfg.init_end,1);
            startIndex = floor((startIndex-1)/samplesPerCycle)* ...
                samplesPerCycle+1;
            for cycleStart = startIndex:samplesPerCycle: ...
                    (numel(time)-samplesPerCycle+1)
                index = cycleStart:(cycleStart+samplesPerCycle-1);
                [X,y] = coupling_regressor(data,ref,index,selfPF);
                R = X'*X;
                z = X'*y;
                localLs = (R+1e-10*eye(2))\z;
                innovation = norm((localLs-c)./[5;5]);
                lambda = cfg.lambda_max- ...
                    (cfg.lambda_max-cfg.lambda_min)* ...
                    min(max(innovation/0.20,0),1);
                [Ein,~] = ...
                    M4WeightedInformationUpdateTest.residualComponents( ...
                    data,ref,index,c,selfPF,cfg.f);
                if isnan(baseIn)
                    baseIn = Ein;
                end
                J = lambda*J+R;
                h = lambda*h+z;
                cRaw = (J+1e-10*eye(2))\h;
                deltaRaw = cRaw-c;
                deltaRate = max(min(deltaRaw, ...
                    cfg.rate_limit_pF_per_cycle), ...
                    -cfg.rate_limit_pF_per_cycle);
                cAfterRate = c+deltaRate;
                cFinal = min(max(cAfterRate, ...
                    cfg.coupling_bounds_pF(1)), ...
                    cfg.coupling_bounds_pF(2));
                rateActive = any(deltaRate ~= deltaRaw);
                projectionActive = any(cFinal ~= cAfterRate);
                c = cFinal;
                if Ein < 1.08*baseIn
                    baseIn = 0.985*baseIn+0.015*Ein;
                end
                row = struct('J_11',J(1,1),'J_12',J(1,2), ...
                    'J_21',J(2,1),'J_22',J(2,2), ...
                    'h_1',h(1),'h_2',h(2), ...
                    'rate_limit_active',logical(rateActive), ...
                    'projection_active',logical(projectionActive));
                if isempty(rows)
                    rows = row;
                else
                    rows(end+1,1) = row; %#ok<AGROW>
                end
            end
            reference = struct2table(rows);
        end

        function [Ein,Equad] = residualComponents( ...
                data,ref,index,c,selfPF,frequency)
            [X,y] = coupling_regressor(data,ref,index,selfPF);
            residual = y-X*c;
            pointsPerPhase = numel(index);
            time = data.t(index);
            omega = 2*pi*frequency;
            phase = [2*pi/3,0,-2*pi/3];
            EinPerPhase = zeros(3,1);
            EquadPerPhase = zeros(3,1);
            for phaseIndex = 1:3
                phaseRows = (phaseIndex-1)*pointsPerPhase+1: ...
                    phaseIndex*pointsPerPhase;
                phaseResidual = residual(phaseRows);
                inPhaseBasis = [ ...
                    sin(omega*time+ref.phi1+phase(phaseIndex)), ...
                    sin(3*omega*time+ref.phi3)];
                quadratureBasis = [ ...
                    cos(omega*time+ref.phi1+phase(phaseIndex)), ...
                    cos(3*omega*time+ref.phi3)];
                basis = [inPhaseBasis,quadratureBasis, ...
                    ones(pointsPerPhase,1)];
                coefficients = basis\phaseResidual;
                EinPerPhase(phaseIndex) = sqrt(mean( ...
                    (inPhaseBasis*coefficients(1:2)).^2));
                EquadPerPhase(phaseIndex) = sqrt(mean( ...
                    (quadratureBasis*coefficients(3:4)).^2));
            end
            Ein = sqrt(mean(EinPerPhase.^2));
            Equad = sqrt(mean(EquadPerPhase.^2));
        end

