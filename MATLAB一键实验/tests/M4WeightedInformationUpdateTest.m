            result = track_coupling_m4_weighted_rls( ...
                data,ref,cfg,selfPF,options);

            testCase.verifyEqual(result.cycle.update_weight, ...
                0.5*ones(height(result.cycle),1),'AbsTol',0);
            testCase.verifyEqual( ...
                result.cycle{:,{'J_increment_applied_11', ...
                'J_increment_applied_12','J_increment_applied_21', ...
                'J_increment_applied_22'}}, ...
                0.5*result.cycle{:,{'J_increment_raw_11', ...
                'J_increment_raw_12','J_increment_raw_21', ...
                'J_increment_raw_22'}}, ...
                'RelTol',5e-14,'AbsTol',1e-20);
            testCase.verifyEqual( ...
                result.cycle{:,{'h_increment_applied_1', ...
                'h_increment_applied_2'}}, ...
                0.5*result.cycle{:,{'h_increment_raw_1', ...
                'h_increment_raw_2'}}, ...
                'RelTol',5e-14,'AbsTol',1e-20);
            testCase.verifyEqual( ...
                result.cycle.base_in_increment_applied, ...
                0.5*result.cycle.base_in_increment_candidate, ...
                'RelTol',5e-14,'AbsTol',5e-20);
        end

        function testEvidenceMonotonicity(testCase)
            baseIn = 1;
            Equad = ones(1,101);
            Ein = linspace(0.5,3,101);

            evidence = m4_fault_evidence( ...
                Ein,Equad,baseIn,1.12,1.20,NaN);

            testCase.verifyGreaterThanOrEqual( ...
                diff(evidence.score),-1e-14);
            testCase.verifyLessThanOrEqual( ...
                diff(evidence.update_weight),1e-14);
            testCase.verifyGreaterThan(evidence.update_weight,0);
            testCase.verifyLessThanOrEqual(evidence.update_weight,1);
            testCase.verifyEqual(evidence.update_weight(Ein<=baseIn), ...
                ones(size(evidence.update_weight(Ein<=baseIn))), ...
                'AbsTol',0);
        end

        function testPhaseConsistencyIsMonotonic(testCase)
            baseIn = 1;
            Ein = 1.5*ones(1,101);
            ratioQuad = linspace(0.05,2.0,101);
            Equad = Ein./ratioQuad;

            evidence = m4_fault_evidence( ...
                Ein,Equad,baseIn,1.12,1.20,NaN);

            testCase.verifyGreaterThanOrEqual( ...
                diff(evidence.phase_weight),-1e-14);
            testCase.verifyGreaterThanOrEqual( ...
                diff(evidence.score),-1e-14);
            testCase.verifyLessThanOrEqual( ...
                diff(evidence.update_weight),1e-14);
        end

        function testControlPathHasNoTruthLeakage(testCase)
            trackerSource = fileread( ...
                which('track_coupling_m4_weighted_rls'));
            evidenceSource = fileread(which('m4_fault_evidence'));
            source = [trackerSource,newline,evidenceSource];
            forbidden = [ ...
                'Cs1_true|Cs2_true|fault_factor_true|fault_label|' ...
                'r_fault|counterfactual|Case05|Case06|case_name'];

            matches = regexp(source,forbidden,'match');

            testCase.verifyEmpty(matches);
        end

        function testDirectionDiagnosticsDoNotAffectControl(testCase)
            [data,ref,cfg,selfPF] = ...
                M4WeightedInformationUpdateTest.fixtureData();
            enabled = struct('forced_update_weight',0.5, ...
                'direction_diagnostics_enabled',true);
            disabled = struct('forced_update_weight',0.5, ...
                'direction_diagnostics_enabled',false);
            controlVariables = { ...
                'Cs1_pF','Cs2_pF','lambda','base_in', ...
                'fault_evidence_score','update_weight', ...
                'delta_c_raw_1','delta_c_raw_2', ...
                'delta_c_applied_1','delta_c_applied_2', ...
                'J_11','J_12','J_21','J_22','h_1','h_2'};

            resultEnabled = track_coupling_m4_weighted_rls( ...
                data,ref,cfg,selfPF,enabled);
            resultDisabled = track_coupling_m4_weighted_rls( ...
                data,ref,cfg,selfPF,disabled);

            testCase.verifyEqual(resultEnabled.hist,resultDisabled.hist, ...
                'AbsTol',0);
            testCase.verifyEqual( ...
                resultEnabled.cycle{:,controlVariables}, ...
                resultDisabled.cycle{:,controlVariables},'AbsTol',0);
            testCase.verifyFalse( ...
                any(resultDisabled.cycle.direction_candidate_valid));
            testCase.verifyTrue(all(isnan( ...
                resultDisabled.cycle.cos_local_fault)));
            testCase.verifyTrue(all(isnan( ...
                resultDisabled.cycle.cos_raw_fault)));
        end

        function testRequiredLogSchemaIsPresent(testCase)
