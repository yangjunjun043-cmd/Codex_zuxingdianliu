function run = execute_legacy_request(paths,request)
if request.CsAC_pF ~= 0
    error('Phase2:LegacyCsAC', ...
        'Nonzero CsAC requires the validated external wrapper path.');
end
registry = phase1a_case_registry();
row = registry.case_name == request.case_name;
if nnz(row) ~= 1
    error('Phase2:LegacyCase', ...
        'Common legacy runner supports one frozen Case01--Case06 case.');
end
caseInfo = registry(row,:);
physicalCfg = patent_default_config();
physicalCfg.model = 'AI6109_MOA_AutoComp9';
physicalCfg.Cself_pF = request.Cself_truth_pF;
algorithmCfg = physicalCfg;
algorithmCfg.Cself_pF = request.Cself_algorithm_pF;

[data,matlabReference] = simulate_phase2_case(physicalCfg, ...
    char(caseInfo.legacy_scenario_name),caseInfo.seed);
ref = reconstruct_refs_from_b(data.t,data.ub,algorithmCfg.f, ...
    algorithmCfg.init_start,algorithmCfg.init_end, ...
    algorithmCfg.phase_error_deg);
[results,inputSignatures] = run_algorithms( ...
    request.algorithms,data,ref,algorithmCfg, ...
    request.Cself_algorithm_pF);
run = struct( ...
    'request',request, ...
    'case_info',caseInfo, ...
    'physical_cfg',physicalCfg, ...
    'algorithm_cfg',algorithmCfg, ...
    'physical_truth_config',struct( ...
        'Cself_truth_pF',request.Cself_truth_pF, ...
        'CsAC_truth_pF',request.CsAC_pF), ...
    'algorithm_assumption_config',struct( ...
        'Cself_algorithm_pF',request.Cself_algorithm_pF), ...
    'data',data, ...
    'matlab_reference',matlabReference, ...
    'ref',ref, ...
    'results',results, ...
    'input_signatures',inputSignatures, ...
    'data_signature',data_signature(data), ...
    'metadata',minimal_metadata(paths));
end

function [results,signatures] = run_algorithms( ...
        modes,data,ref,cfg,algorithmCself)
results = struct();
signatures = strings(numel(modes),1);
signature = data_signature(data);
selfPF = repmat(algorithmCself,1,3);
for k = 1:numel(modes)
    mode = upper(string(modes(k)));
    results.(char(mode)) = run_phase1a_algorithm( ...
        mode,data,ref,cfg,selfPF);
    signatures(k) = signature;
end
end

function metadata = minimal_metadata(paths)
metadata = struct( ...
    'model_sha256',file_sha256(fullfile(paths.matlab_root, ...
        'AI6109_MOA_AutoComp9.slx')), ...
    'run_timestamp',string(datetime('now','TimeZone','Asia/Shanghai', ...
        'Format',"yyyy-MM-dd'T'HH:mm:ssXXX")), ...
    'git_commit',"STEP2A_GATE_VALIDATION", ...
    'git_branch',"N/A", ...
    'git_dirty_status',"RECORDED_SEPARATELY");
end

function signature = data_signature(data)
names = {'t','ua','ub','uc','ia','ib','ic','irA','irB','irC','Cs1','Cs2'};
digester = java.security.MessageDigest.getInstance('SHA-256');
for k = 1:numel(names)
    bytes = typecast(double(data.(names{k})(:)),'uint8');
    digester.update(bytes);
end
hashBytes = typecast(digester.digest(),'uint8');
signature = upper(string(reshape(dec2hex(hashBytes,2).',1,[])));
end

