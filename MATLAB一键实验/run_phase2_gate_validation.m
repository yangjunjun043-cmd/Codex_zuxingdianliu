function output = run_phase2_gate_validation(action,request)
%RUN_PHASE2_GATE_VALIDATION Phase 2 Step 2A execution and gate validation.
% This wrapper separates physical truth from algorithm assumptions and
% delegates all frozen estimation work to the existing Phase 1 functions.
%
% Default:
%   run_phase2_gate_validation
%
% Reusable common-runner entry (after Step 2A authorization):
%   run_phase2_gate_validation("execute",request)
% request fields: case_name, Cself_truth_pF, Cself_algorithm_pF,
% CsAC_pF, algorithms. The execute entry currently supports the frozen
% legacy Case01--Case06 paths; Case08 remains an internal paired anchor.

if nargin < 1 || isempty(action)
    action = "validate_gates";
end
action = lower(string(action));
if ~isscalar(action)
    error('Phase2:Step2AAction','Action must be a scalar string.');
end

matlabRoot = fileparts(mfilename('fullpath'));
projectRoot = fileparts(matlabRoot);
paths = phase2_paths(projectRoot,matlabRoot);
add_required_paths(paths);

if action == "execute"
    if nargin < 2 || ~isstruct(request) || ~isscalar(request)
        error('Phase2:Step2ARequest', ...
            'The execute action requires one scalar request struct.');
    end
    integrity = capture_frozen_integrity(paths);
    if ~integrity.pass
        error('Phase2:FrozenIntegrity', ...
            'Frozen integrity failed; the common runner is unavailable.');
    end
    output = execute_legacy_request(paths,normalize_request(request));
    return
elseif action ~= "validate_gates"
    error('Phase2:Step2AAction','Unsupported action: %s.',action);
end

if ~isfolder(paths.output_root)
    mkdir(paths.output_root);
end
records = empty_records();
pre = capture_frozen_integrity(paths);
preTag = integrity_tag(pre);
records = append_integrity_records(records,pre,"PRE",preTag,"");

commonPass = false;
cselfPass = false;
csacPass = false;
details = struct();
details.error = "";
details.anchor_algorithm_evaluations = 0;
details.case08_branch_runs = 0;
details.optional_linearity_pass = false;

if pre.pass
    try
        [commonRecords,common,commonPass,commonDetails] = ...
            validate_common_runner(paths);
        records = [records;commonRecords];
        details.common = commonDetails;
        details.anchor_algorithm_evaluations = 11;
        details.case08_branch_runs = 2;

        if commonPass
            [cselfRecords,cselfPass,cselfDetails] = ...
                validate_cself_split(paths,common);
            records = [records;cselfRecords];
            details.cself = cselfDetails;

            [csacRecords,csacPass,csacDetails] = ...
                validate_csac_wrapper(common);
            records = [records;csacRecords];
            details.csac = csacDetails;
            details.optional_linearity_pass = ...
                csacDetails.optional_linearity_pass;
        else
            records = append_not_run(records, ...
                "CSELF_SPLIT_INTERFACE_GATE", ...
                "COMMON_RUNNER_EQUIVALENCE_GATE failed");
            records = append_not_run(records, ...
                "ZERO_INJECTION_REGRESSION", ...
                "COMMON_RUNNER_EQUIVALENCE_GATE failed");
        end
    catch exception
        details.error = string(getReport(exception,'extended', ...
            'hyperlinks','off'));
        records = add_record(records,"STEP2A_EXCEPTION", ...
            "COMMON_RUNNER_EQUIVALENCE_GATE","N/A","N/A", ...
            "EXECUTION_EXCEPTION",NaN,NaN,NaN,"runner", ...
            "exception_free_execution",1,0,0,false, ...
            string(exception.identifier)+": "+string(exception.message));
        commonPass = false;
        cselfPass = false;
        csacPass = false;
    end
else
    details.error = "PRE frozen integrity check failed; no simulation executed.";
    records = append_not_run(records, ...
        "COMMON_RUNNER_EQUIVALENCE_GATE",details.error);
    records = append_not_run(records, ...
        "CSELF_SPLIT_INTERFACE_GATE",details.error);
    records = append_not_run(records, ...
        "ZERO_INJECTION_REGRESSION",details.error);
end

post = capture_frozen_integrity(paths);
postTag = integrity_tag(post);
records = append_integrity_records(records,post,"POST",preTag,postTag);
sourcePass = pre.pass && post.pass && ...
    isequal(pre.actual_sha256,post.actual_sha256);

records.frozen_hash_pre(:) = preTag;
records.frozen_hash_post(:) = postTag;
gate = struct( ...
    'source',sourcePass, ...
    'common',commonPass, ...
    'cself',cselfPass, ...
    'csac',csacPass);
[readyCount,pendingCount] = authorized_condition_counts( ...
    paths.condition_registry,gate);
status = final_status(gate);

writetable(records,paths.results_csv);
write_report(paths,records,pre,post,gate,status, ...
    readyCount,pendingCount,details);

output = struct( ...
    'status',status, ...
    'gates',gate, ...
    'ready_condition_count',readyCount, ...
    'pending_or_blocked_condition_count',pendingCount, ...
    'results_csv',string(paths.results_csv), ...
    'report',string(paths.report), ...
    'full_matrix_executed',false);

fprintf('NO_FROZEN_SOURCE_DIFF_GATE=%s\n',pass_label(gate.source));
fprintf('COMMON_RUNNER_EQUIVALENCE_GATE=%s\n',pass_label(gate.common));
fprintf('CSELF_SPLIT_INTERFACE_GATE=%s\n',pass_label(gate.cself));
fprintf('ZERO_INJECTION_REGRESSION=%s\n',pass_label(gate.csac));
fprintf('STEP2A_STATUS=%s\n',status);
fprintf('READY_CONDITION_COUNT=%d\n',readyCount);
fprintf('PENDING_OR_BLOCKED_CONDITION_COUNT=%d\n',pendingCount);
fprintf('STEP2A_RESULTS=%s\n',paths.results_csv);
fprintf('STEP2A_REPORT=%s\n',paths.report);
end

