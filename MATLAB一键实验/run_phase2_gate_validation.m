    return
end
allowed = true(height(registry),1);
if ~gate.cself
    allowed(contains(registry.execution_gate, ...
        "CSELF_SPLIT_INTERFACE_GATE")) = false;
end
if ~gate.csac
    allowed(contains(registry.execution_gate, ...
        "ZERO_INJECTION_REGRESSION")) = false;
end
ready = nnz(allowed);
pending = height(registry)-ready;
end

function status = final_status(gate)
if ~(gate.source && gate.common)
    status = "BLOCKED";
elseif gate.cself && gate.csac
    status = "PASS";
else
    status = "PARTIAL";
end
end

