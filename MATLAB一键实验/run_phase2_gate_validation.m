function request = normalize_request(request)
required = ["case_name","Cself_truth_pF","Cself_algorithm_pF", ...
    "CsAC_pF","algorithms"];
for name = required
    if ~isfield(request,char(name))
        error('Phase2:Step2ARequest','Missing request field %s.',name);
    end
end
request.case_name = string(request.case_name);
request.algorithms = string(request.algorithms(:));
numericNames = ["Cself_truth_pF","Cself_algorithm_pF","CsAC_pF"];
for name = numericNames
    value = request.(char(name));
    if ~isnumeric(value) || ~isscalar(value) || ~isfinite(value)
        error('Phase2:Step2ARequest','%s must be finite scalar.',name);
    end
end
if request.CsAC_pF ~= 0
    error('Phase2:Step2ARequest', ...
        ['The public execute action enables nonzero CsAC only after ' ...
         'a future registry-driven runner calls the validated wrapper.']);
end
end

function integrity = capture_frozen_integrity(paths)
manifest = read_csv_table(paths.manifest);
countPhase1 = height(manifest);
labels = strings(countPhase1+3,1);
filePaths = strings(countPhase1+3,1);
expected = strings(countPhase1+3,1);
actual = strings(countPhase1+3,1);
mode = repmat("RAW_SHA256",countPhase1+3,1);

for k = 1:countPhase1
    labels(k) = "PHASE1_MANIFEST:"+manifest.roles(k)+":"+ ...
        manifest.relative_path(k);
    filePaths(k) = fullfile(paths.project_root, ...
        char(manifest.relative_path(k)));
    expected(k) = upper(manifest.sha256(k));
    actual(k) = file_sha256(filePaths(k));
end

labels(countPhase1+1) = "STEP1_SPECIFICATION";
filePaths(countPhase1+1) = paths.specification;
expected(countPhase1+1) = ...
    "9FAB573BCE6D5D0A1F3F6A569771F5B1C69706AB6E6E38FD97843BF41B931531";
actual(countPhase1+1) = canonical_specification_sha256( ...
    paths.specification);
mode(countPhase1+1) = "CANONICAL_SELF_HASH";

labels(countPhase1+2) = "STEP1_CONDITION_REGISTRY";
filePaths(countPhase1+2) = paths.condition_registry;
expected(countPhase1+2) = ...
    "8A498E19A455C13CAA7B5371BE2F933CA7B7637B893C656C92DA84D88D1938BE";
actual(countPhase1+2) = file_sha256(filePaths(countPhase1+2));

labels(countPhase1+3) = "STEP1_EXECUTION_REGISTRY";
filePaths(countPhase1+3) = paths.execution_registry;
expected(countPhase1+3) = ...
    "974B8874404C46C4B549CAD8E2D52CCCC7F1D4F81D68AF8911201307230394D7";
actual(countPhase1+3) = file_sha256(filePaths(countPhase1+3));

pass = expected == actual;
integrity = struct( ...
    'labels',labels, ...
    'paths',filePaths, ...
    'modes',mode, ...
    'expected_sha256',expected, ...
    'actual_sha256',actual, ...
    'item_pass',pass, ...
    'phase1_count',countPhase1, ...
    'phase1_pass_count',nnz(pass(1:countPhase1)), ...
    'step1_pass_count',nnz(pass(countPhase1+1:end)), ...
    'pass',all(pass));
end

function hash = canonical_specification_sha256(path)
textValue = fileread(path);
pattern = '(specification_sha256_canonical:\s*)[0-9A-Fa-f]{64}';
replacement = '$1<SELF_SHA256_CANONICAL_PLACEHOLDER>';
canonical = regexprep(textValue,pattern,replacement,'once');
if strcmp(canonical,textValue)
    error('Phase2:CanonicalHash', ...
        'Specification canonical self-hash field was not found.');
end
hash = bytes_sha256(unicode2native(canonical,'UTF-8'));
end

function hash = file_sha256(path)
fileId = fopen(path,'rb');
if fileId < 0
    error('Phase2:HashRead','Unable to open %s.',path);
end
cleanup = onCleanup(@() fclose(fileId));
bytes = fread(fileId,Inf,'*uint8');
hash = bytes_sha256(bytes);
end

function hash = bytes_sha256(bytes)
digester = java.security.MessageDigest.getInstance('SHA-256');
digester.update(uint8(bytes));
hashBytes = typecast(digester.digest(),'uint8');
hash = upper(string(reshape(dec2hex(hashBytes,2).',1,[])));
end

function tag = integrity_tag(integrity)
tag = sprintf('%d/%d %s',nnz(integrity.item_pass), ...
    numel(integrity.item_pass),pass_label(integrity.pass));
end

function records = append_integrity_records( ...
        records,integrity,variant,preTag,postTag)
for k = 1:numel(integrity.labels)
    records = add_record(records, ...
        "HASH_"+variant+"_"+compose('%02d',k), ...
        "NO_FROZEN_SOURCE_DIFF_GATE","N/A","N/A",variant, ...
        NaN,NaN,NaN,string(integrity.paths(k)), ...
        integrity.modes(k),NaN,NaN,0,integrity.item_pass(k), ...
        "expected="+integrity.expected_sha256(k)+ ...
        "; actual="+integrity.actual_sha256(k));
end
if strlength(preTag) > 0
    records.frozen_hash_pre(:) = preTag;
end
if strlength(postTag) > 0
    records.frozen_hash_post(:) = postTag;
end
end

function [records,common,gatePass,details] = validate_common_runner(paths)
records = empty_records();
tol = 1e-12;
truthTol = 1e-10;

request02 = standard_request("Case02_slow_drift",400,400,0, ...
    ["M0" "M2" "M3" "M4"]);
request05 = standard_request("Case05_fault_only",400,400,0, ...
    ["M0" "M2" "M3" "M4"]);
common.case02 = execute_legacy_request(paths,request02);
common.case05 = execute_legacy_request(paths,request05);
common.case08 = execute_case08_anchor(paths);

baseline = load(fullfile(paths.project_root,'paper_research', ...
    'phase1a_baseline','baseline_workspace.mat'), ...
    'caseData','algorithmResults');
step3 = load(fullfile(paths.step3_root,'workspace', ...
    'normal_tracking_workspace.mat'),'caseDetails');
step4 = load(fullfile(paths.step4_root,'workspace', ...
    'fault_preservation_workspace.mat'),'caseDetails');
step5b = load(fullfile(paths.step5b_root,'workspace', ...
    'case08_step5b_workspace.mat'),'caseDetail');

baselineTable = read_csv_table(fullfile(paths.project_root,'paper_research', ...
    'phase1a_baseline','baseline_summary.csv'));
normalTable = read_csv_table(fullfile(paths.step3_root,'tables', ...
    'normal_tracking_summary.csv'));
faultTable = read_csv_table(fullfile(paths.step4_root,'tables', ...
    'fault_preservation_summary.csv'));

% Case02: M0--M3 use the Phase 1A workspace; M4 uses Phase 1C Step 3.
for mode = ["M0" "M2" "M3" "M4"]
    current = common.case02.results.(char(mode));
    if mode == "M4"
        detail = step3.caseDetails.Case02_slow_drift;
        frozenCHist = detail.M4_cHist;
        frozenIrB = detail.M4_irB;
        frozenCycle = detail.M4_cycle;
        formal = normalTable(normalTable.case_name == ...
            "Case02_slow_drift" & normalTable.algorithm_mode == mode,:);
    else
        detail = baseline.algorithmResults.Case02_slow_drift.(char(mode));
        frozenCHist = detail.cHist;
        frozenIrB = detail.irB;
        if isfield(detail,'cycle'), frozenCycle = detail.cycle;
        else, frozenCycle = table(); end
        formal = baselineTable(baselineTable.case_name == ...
            "Case02_slow_drift" & baselineTable.algorithm_mode == mode,:);
    end
    records = compare_algorithm_trajectory(records,"C02_"+mode, ...
        "Case02_slow_drift",mode,current,frozenCHist,frozenIrB,tol);
    records = compare_cycle_state(records,"C02_"+mode, ...
        "Case02_slow_drift",mode,current,frozenCycle,tol);
    evaluated = evaluate_phase1a_metrics(common.case02.case_info, ...
        current,common.case02.data,common.case02.algorithm_cfg, ...
        common.case02.metadata);
    for metric = ["Cs1_RMSE_pF" "Cs2_RMSE_pF" ...
            "B_resistive_fundamental_error_pct"]
        records = compare_scalar(records,"C02_"+mode+"_"+metric, ...
            "COMMON_RUNNER_EQUIVALENCE_GATE","Case02_slow_drift", ...
            mode,"NOMINAL",400,400,0,"formal primary metric",metric, ...
            formal.(char(metric)),evaluated.(char(metric)),tol,"");
    end
end

truth02 = baseline.caseData.Case02_slow_drift;
records = compare_scalar(records,"C02_TRUTH_CS1", ...
    "COMMON_RUNNER_EQUIVALENCE_GATE","Case02_slow_drift","ALL", ...
    "NOMINAL",400,400,0,"physical truth","Cs1 trajectory max diff", ...
    0,max(abs(common.case02.data.Cs1-truth02.Cs1_true)),truthTol,"");
records = compare_scalar(records,"C02_TRUTH_CS2", ...
    "COMMON_RUNNER_EQUIVALENCE_GATE","Case02_slow_drift","ALL", ...
    "NOMINAL",400,400,0,"physical truth","Cs2 trajectory max diff", ...
    0,max(abs(common.case02.data.Cs2-truth02.Cs2_true)),truthTol,"");

% Case05: M0--M3 use the Phase 1A workspace; M4 uses Phase 1C Step 4.
for mode = ["M0" "M2" "M3" "M4"]
    current = common.case05.results.(char(mode));
    if mode == "M4"
        detail = step4.caseDetails.Case05_fault_only;
        frozenCHist = detail.M4_cHist;
        frozenIrB = detail.M4_irB;
        frozenCycle = detail.M4_cycle;
        formal = faultTable(faultTable.case_name == ...
            "Case05_fault_only" & faultTable.algorithm_mode == mode,:);
    else
        detail = baseline.algorithmResults.Case05_fault_only.(char(mode));
        frozenCHist = detail.cHist;
        frozenIrB = detail.irB;
        if mode == "M3"
            frozenCycle = step4.caseDetails.Case05_fault_only.M3_cycle;
        elseif isfield(detail,'cycle')
            frozenCycle = detail.cycle;
        else
            frozenCycle = table();
        end
        formal = baselineTable(baselineTable.case_name == ...
            "Case05_fault_only" & baselineTable.algorithm_mode == mode,:);
    end
    records = compare_algorithm_trajectory(records,"C05_"+mode, ...
        "Case05_fault_only",mode,current,frozenCHist,frozenIrB,tol);
    records = compare_cycle_state(records,"C05_"+mode, ...
        "Case05_fault_only",mode,current,frozenCycle,tol);
    evaluated = evaluate_phase1a_metrics(common.case05.case_info, ...
        current,common.case05.data,common.case05.algorithm_cfg, ...
        common.case05.metadata);
    records = compare_scalar(records,"C05_"+mode+"_FACTOR", ...
        "COMMON_RUNNER_EQUIVALENCE_GATE","Case05_fault_only",mode, ...
        "NOMINAL",400,400,0,"formal primary metric", ...
        "fault_factor_est",formal.fault_factor_est, ...
        evaluated.fault_factor_est,tol,"");
    if mode ~= "M4"
        for metric = ["Cs1_RMSE_pF" "Cs2_RMSE_pF" ...
                "B_resistive_fundamental_error_pct"]
            records = compare_scalar(records, ...
                "C05_"+mode+"_"+metric, ...
                "COMMON_RUNNER_EQUIVALENCE_GATE", ...
                "Case05_fault_only",mode,"NOMINAL",400,400,0, ...
                "formal primary metric",metric,formal.(char(metric)), ...
                evaluated.(char(metric)),tol,"");
        end
    end
end

% Case08 paired F/CF anchor; no M0 historical-equivalence claim.
for mode = ["M2" "M3" "M4"]
    currentF = common.case08.resultsF.(char(mode));
    currentCF = common.case08.resultsCF.(char(mode));
    frozenF = step5b.caseDetail.(char(mode+"_cHist_F"));
    frozenCF = step5b.caseDetail.(char(mode+"_cHist_CF"));
    frozenIrBF = step5b.caseDetail.(char(mode+"_irB_F"));
    frozenIrBCF = step5b.caseDetail.(char(mode+"_irB_CF"));
    records = compare_algorithm_trajectory(records,"C08_F_"+mode, ...
        "Case08_overlap_drift_fault_f160",mode,currentF, ...
        frozenF,frozenIrBF,tol);
    records = compare_algorithm_trajectory(records,"C08_CF_"+mode, ...
        "Case08_overlap_drift_fault_f160",mode,currentCF, ...
        frozenCF,frozenIrBCF,tol);
    if mode == "M3"
        frozenCycle = step5b.caseDetail.M3_cycle_F;
    elseif mode == "M4"
        frozenCycle = step5b.caseDetail.M4_cycle_F;
    else
        frozenCycle = table();
    end
    records = compare_cycle_state(records,"C08_"+mode, ...
        "Case08_overlap_drift_fault_f160",mode,currentF, ...
        frozenCycle,tol);
end

records = compare_case08_metrics(records,paths,common.case08,tol);
gatePass = all(records.pass);
details = struct( ...
    'case02_seed',common.case02.case_info.seed, ...
    'case05_seed',common.case05.case_info.seed, ...
    'case08_seed',common.case08.definition.seed, ...
    'anchor_algorithm_evaluations',11, ...
    'case08_matched_branches',2, ...
    'row_count',height(records), ...
    'pass_count',nnz(records.pass), ...
    'max_numeric_difference',max(records.absolute_difference,[], ...
        'omitmissing'));
end

