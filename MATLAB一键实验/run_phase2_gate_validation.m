    line(sprintf('- AC1 formula maximum error: %.17g A.', ...
        details.csac.ac1_formula_max_error_A));
    line(sprintf('- AC1 three-phase conservation maximum error: %.17g A.', ...
        details.csac.ac1_conservation_max_error_A));
    line(sprintf('- Optional 0.5-to-1.0 pF linearity error: %.17g A (%s).', ...
        details.csac.optional_linearity_error_A, ...
