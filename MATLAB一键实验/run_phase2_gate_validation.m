    line(sprintf('- AC0 maximum noisy-current difference: %.17g A.', ...
        details.csac.ac0_noisy_max_difference_A));
end
line(['- AC0 compares ideal/noisy currents, truth, references, and formal ' ...
    'M0/M2/M3/M4 outputs against the nominal Case02 path.']);
