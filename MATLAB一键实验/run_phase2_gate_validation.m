function [data,metadata] = external_csac_wrapper( ...
        cleanData,cleanReference,nominalNoisyData,CsACpF,snrDB,seed)
data = cleanData;
duA = gradient(cleanData.ua,cleanData.t);
duC = gradient(cleanData.uc,cleanData.t);
contribution = CsACpF*1e-12*(duA-duC);
ideal = cleanData;
ideal.ia = cleanData.ia+contribution;
ideal.ib = cleanData.ib;
ideal.ic = cleanData.ic-contribution;

% The frozen nominal path computes measurement-noise sigma from the
% analytic MATLAB reference current. Reusing that exact basis is required
% for AC0 identity; the same CsAC contribution is applied before sigma is
% computed for every nonzero injection.
noiseBasis = cleanReference;
noiseBasis.ia = cleanReference.ia+contribution;
noiseBasis.ib = cleanReference.ib;
noiseBasis.ic = cleanReference.ic-contribution;

sigma = struct( ...
    'A',rms(noiseBasis.ia)/10^(snrDB/20), ...
    'B',rms(noiseBasis.ib)/10^(snrDB/20), ...
    'C',rms(noiseBasis.ic)/10^(snrDB/20));
rng(seed+10000);
noise = struct( ...
    'A',sigma.A*randn(size(ideal.ia)), ...
    'B',sigma.B*randn(size(ideal.ib)), ...
    'C',sigma.C*randn(size(ideal.ic)));
if CsACpF == 0
    % A zero external contribution is an identity operation. Preserve the
    % frozen nominal noisy data byte-for-byte rather than changing floating
    % point operation order by reconstructing clean + noise externally.
    data = nominalNoisyData;
    noise = struct( ...
        'A',data.ia-ideal.ia, ...
        'B',data.ib-ideal.ib, ...
        'C',data.ic-ideal.ic);
else
    data.ia = ideal.ia+noise.A;
    data.ib = ideal.ib+noise.B;
    data.ic = ideal.ic+noise.C;
end
data.CsAC_pF = CsACpF*ones(size(data.t));
data.current_source = "phase2_external_csac_wrapper";
expectedSigma = struct( ...
    'A',rms(noiseBasis.ia)/10^(snrDB/20), ...
    'B',rms(noiseBasis.ib)/10^(snrDB/20), ...
    'C',rms(noiseBasis.ic)/10^(snrDB/20));
metadata = struct( ...
    'ideal',ideal,'noise_basis',noiseBasis,'noise',noise,'sigma',sigma, ...
    'expected_sigma',expectedSigma,'duA',duA,'duC',duC, ...
    'seed',seed,'rng_seed',seed+10000,'snr_db',snrDB, ...
    'injection_order',"ideal current -> CsAC contribution -> noise sigma -> noise");
end

