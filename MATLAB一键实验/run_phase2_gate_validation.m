    blank();
    line('Execution note: `'+replace(details.error,newline,' ')+'`');
end
end

function value = authorization(pass)
if pass, value = "AUTHORIZED"; else, value = "BLOCKED"; end
end

function value = yes_no(pass)
if pass, value = "YES"; else, value = "NO"; end
end

function label = pass_label(pass)
if pass, label = "PASS"; else, label = "FAIL"; end
end

