function records = compare_scalar(records,testId,gateName,caseName,mode, ...
        variant,truthCself,algorithmCself,csac,target,metric, ...
        referenceValue,testValue,tolerance,notes)
if isscalar(referenceValue) && isscalar(testValue) && ...
        isfinite(referenceValue) && isfinite(testValue)
    absoluteDifference = abs(double(testValue)-double(referenceValue));
    pass = absoluteDifference <= tolerance;
else
    pass = isequaln(referenceValue,testValue);
end
records = add_record(records,testId,gateName,caseName,mode,variant, ...
    truthCself,algorithmCself,csac,target,metric,referenceValue, ...
    testValue,tolerance,pass,notes);
end

function records = add_record(records,testId,gateName,caseName,mode, ...
        variant,truthCself,algorithmCself,csac,target,metric, ...
        referenceValue,testValue,tolerance,pass,notes)
if isfinite(referenceValue) && isfinite(testValue)
    absoluteDifference = abs(double(testValue)-double(referenceValue));
    relativeDifference = absoluteDifference/(abs(double(referenceValue))+eps);
else
    absoluteDifference = NaN;
    relativeDifference = NaN;
end
row = table(string(testId),string(gateName),string(caseName), ...
    string(mode),string(variant),double(truthCself), ...
    double(algorithmCself),double(csac),string(target),string(metric), ...
    double(referenceValue),double(testValue),absoluteDifference, ...
    relativeDifference,double(tolerance),logical(pass),"","", ...
    string(notes),'VariableNames',records.Properties.VariableNames);
records = [records;row];
end

