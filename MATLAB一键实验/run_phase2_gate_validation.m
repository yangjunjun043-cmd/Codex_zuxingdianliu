blank();
line(sprintf('- Phase 1 manifest: %d/%d PASS.', ...
    pre.phase1_pass_count,pre.phase1_count));
line(sprintf('- Phase 2 Step 1 final files: %d/3 PASS.', ...
    pre.step1_pass_count));
line('- Specification verification used the frozen canonical self-hash rule.');
line('- PRE result: **'+pass_label(pre.pass)+'**.');
blank();
line('## 3. Common runner architecture');
blank();
line(['The wrapper exposes separate `physical_truth_config.Cself_truth_pF` ' ...
    'and `algorithm_assumption_config.Cself_algorithm_pF`. Physical data ' ...
    'generation receives only the truth value; the frozen dispatcher receives ' ...
