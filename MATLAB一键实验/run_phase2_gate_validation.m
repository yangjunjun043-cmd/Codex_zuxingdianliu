    records = add_record(records,idPrefix+"_STATE_NA", ...
        "COMMON_RUNNER_EQUIVALENCE_GATE",caseName,mode,"NOMINAL", ...
        400,400,0,"frozen state evidence","state trajectory", ...
        NaN,NaN,tol,true,"NOT_AVAILABLE_IN_FROZEN_EVIDENCE");
    return
end
if ~isfield(current,'tracker') || ~isfield(current.tracker,'cycle')
    records = add_record(records,idPrefix+"_STATE_MISSING", ...
        "COMMON_RUNNER_EQUIVALENCE_GATE",caseName,mode,"NOMINAL", ...
        400,400,0,"frozen state evidence","state trajectory", ...
        0,Inf,tol,false,"Current tracker state is missing.");
    return
end
currentCycle = current.tracker.cycle;
for name = ["lambda" "gate" "update_weight"]
    if ismember(name,string(frozenCycle.Properties.VariableNames)) && ...
            ismember(name,string(currentCycle.Properties.VariableNames))
        difference = max(abs(currentCycle.(char(name))- ...
            frozenCycle.(char(name))));
